/**
 * Нулевой байт в тексте: граница самой базы, а не вкус схемы.
 *
 * PostgreSQL не принимает `NUL` ни в одну текстовую колонку — запрос
 * падает `22021` в драйвере, то есть `500` вместо отказа с объяснением.
 * Поэтому проверка живёт в контракте, рядом со всеми остальными: там, где
 * её нельзя забыть на одном из путей записи.
 *
 * Общего запрета управляющих символов здесь **нет** намеренно. Текст
 * саммари приводится к пригодному виду своей функцией
 * (`normalizeSummaryText`), потому что он уезжает наружу к модели; хроника
 * же принимает любой текст, который база способна сохранить, и сужать это
 * до «печатных символов» значило бы решать за человека, что он написал.
 */

/** Нет ли в строке нулевого байта. */
export function isNulFree(value: string): boolean {
  return !value.includes('\u0000');
}

/** Объяснение отказа: формулировка контракта, а не текст zod. */
export const HAS_NUL = 'Нулевой байт в тексте недопустим';
