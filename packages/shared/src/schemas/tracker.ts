import { z } from 'zod';

import { ModelProbeOutcome, TaskExportOutcome, TrackerKind } from '../enums';

/**
 * Трекер не настроен: выгружать некуда и спрашивать некого.
 *
 * Отдаётся `409`, а не `404`: подключение — настройка установки, его
 * отсутствие не секрет и не повод скрывать существование проекта.
 */
export const TRACKER_NOT_CONFIGURED = 'tracker_not_configured';

/**
 * У проекта нет привязки доски: класть задачу некуда.
 *
 * Отдельно от {@link TRACKER_NOT_CONFIGURED}, потому что чинится другим
 * человеком и на другом экране: подключение — суперадмином на `/settings`,
 * привязку ставит тот, у кого есть запись на «Роадмап» своего проекта.
 * Сведение их в «трекер не готов» послало бы подрядчика к администратору
 * за тем, что он может сделать сам (дизайн, 3.5).
 */
export const TRACKER_BINDING_MISSING = 'tracker_binding_missing';

/** Трекер не ответил: сеть, таймаут, `5xx`, `429`. Повторить можно. */
export const TRACKER_UNAVAILABLE = 'tracker_unavailable';

/**
 * Трекер ответил отказом: токен не принят, доски нет, тело не по формату.
 *
 * Отдельно от {@link TRACKER_UNAVAILABLE}, потому что различие — в том, что
 * делать: «не ответил» лечится повтором, «отказал» — правкой настройки.
 * Тела чужого ответа в отказе нет никогда: в нём бывает и эхо присланного,
 * и сам токен в сообщении о неверном заголовке.
 */
export const TRACKER_REJECTED = 'tracker_rejected';

/**
 * Адрес подключения негоден: не `https`, строка запроса или данные входа.
 *
 * Свой код рядом с четырьмя кодами обмена: те отвечают на «что случилось
 * при выгрузке», этот — на «почему форма не сохраняется», и человек по ним
 * делает разное.
 */
export const TRACKER_BAD_URL = 'tracker_bad_url';

/**
 * Почему трекер не работает — значения поля `blockedBy`.
 *
 * Код, а не фраза, как у узлов модели: код интерфейс разбирает, фразу можно
 * переписать. Причины не сводятся в «не настроено», потому что чинятся
 * разным действием: токен берут в Weeek, адрес вписывают,
 * `CAIRN_ENCRYPTION_KEY` возвращают прежний, а галочку ставят обратно.
 */
/** Токена нет: без него порт выключен и кнопки выгрузки нет вовсе. */
export const TRACKER_SECRET_MISSING = 'secret_missing';
/**
 * Адреса нет — то же состояние, что «строки подключения нет вовсе».
 *
 * Отдельного вида источника, как `ModelServiceSource` у узлов модели, здесь
 * не бывает: запасного источника в окружении у трекера нет и не будет
 * (дизайн, 3.4), и единственный ответ на вопрос «откуда настройка» — база.
 * Поэтому ненастроенное подключение проецируется пустым адресом и этим
 * кодом, а не отдельным полем.
 */
export const TRACKER_BASE_URL_MISSING = 'base_url_missing';
/** Токен есть, но расшифровать его нечем: подменён `CAIRN_ENCRYPTION_KEY`. */
export const TRACKER_SECRET_UNDECRYPTABLE = 'secret_undecryptable';
/** Настройка полна, но человек снял галочку. */
export const TRACKER_DISABLED = 'disabled';

/**
 * Разбирает адрес подключения трекера.
 *
 * Не вызов `parseModelServiceBaseUrl` с `placement: external`, и это не
 * недосмотр: у того в сигнатуре стоит размещение, которого у трекера нет
 * вовсе — колонки `placement` в `tracker_connections` не появилось, —
 * а его коды отказов названы узлом модели и уехали бы в текст отказа
 * трекера. Поведение здесь **строже**: `https` безусловен, потому что
 * ветки «свой узел в контуре», в которой `http` оправдан, у чужого
 * облачного трекера не бывает.
 *
 * Запрет на строку запроса и на `user:pass@` — тот же инвариант, что у
 * узлов модели: ровно так токен попадает в адрес, а из адреса он уехал бы
 * и на экран, и в журнал, и в текст отказа.
 */
export function parseTrackerBaseUrl(raw: string): string {
  let url: URL;

  try {
    url = new URL(raw.trim());
  } catch {
    throw new Error(TRACKER_BAD_URL);
  }

  if (url.protocol !== 'https:') {
    throw new Error(TRACKER_BAD_URL);
  }

  if (url.search !== '' || url.hash !== '' || url.username !== '' || url.password !== '') {
    throw new Error(TRACKER_BAD_URL);
  }

  // Собирается из разобранных частей, а не из присланной строки: иначе сюда
  // попало бы всё, что `URL` разобрал, но мы не проверяли. Замыкающие косые
  // снимаются, потому что адаптер дописывает `/tm/tasks`, и двойная косая в
  // пути дала бы `404`.
  return `${url.origin}${url.pathname}`.replace(/\/+$/, '');
}

/**
 * Адрес подключения: `https`, без строки запроса и без `userinfo`.
 *
 * Проверка стоит **в схеме**, а не только в службе, в отличие от узлов
 * модели: там форма зовёт `parseModelServiceBaseUrl` сама, чтобы объяснить
 * отказ двумя разными словами, а здесь ветка одна — вписать `https`, — и
 * `400` по схеме говорит ровно это. Заодно проверку нельзя забыть на новом
 * пути записи.
 */
export const trackerBaseUrlSchema = z
  .string()
  .trim()
  .min(1)
  .max(500)
  .refine((raw) => {
    try {
      parseTrackerBaseUrl(raw);
      return true;
    } catch {
      return false;
    }
  }, TRACKER_BAD_URL);

/**
 * Запись подключения трекера целиком.
 *
 * `.strict()` не украшение: `kind` приходит адресом ручки, а не телом —
 * перечень здесь первичный ключ строки, и тело, способное его переписать,
 * правило бы не ту настройку.
 */
export const trackerConnectionUpdateSchema = z
  .object({
    baseUrl: trackerBaseUrlSchema,
    /**
     * Рабочее пространство Weeek. Обнуляемо и работу не блокирует: токен
     * сам принадлежит пространству, и порту этот идентификатор не нужен ни
     * в одной из четырёх операций. Нужен он человеческой ссылке на задачу,
     * которую без живого токена не проверить (дизайн, 10.4), — поэтому
     * пустое значение означает «ссылку соберём из ответа, а не по шаблону»,
     * а не «подключение неполно».
     */
    workspaceId: z.string().trim().max(100).nullable(),
    isEnabled: z.boolean(),
    /**
     * Токен: **поле отсутствует** — не менять, `null` — убрать, строка —
     * поставить. Ровно три состояния, как у ключа узла модели.
     *
     * Пустая строка отвергается схемой намеренно: иначе «убрать токен» и
     * «форма отправила незаполненное поле» были бы одним и тем же, и
     * открыть форму, ничего не трогая, и сохранить значило бы стереть токен.
     */
    secret: z.string().min(1).max(500).nullable().optional(),
  })
  .strict();

/**
 * Действующее подключение трекера. Токена здесь нет никогда.
 *
 * Собирается полем за полем, а не расширением строки базы: токен не выходит
 * ни в один ответ, и единственный способ это удержать — явная проекция.
 */
export const trackerConnectionSchema = z.object({
  kind: z.nativeEnum(TrackerKind),
  /** Пусто означает «строки подключения нет»: см. `TRACKER_BASE_URL_MISSING`. */
  baseUrl: z.string(),
  workspaceId: z.string().nullable(),
  /**
   * Токен задан — и всё, что о нём сообщается.
   *
   * Ни длины, ни хвоста: хвост сужает перебор и не отвечает ни на один
   * вопрос, на который не отвечает «задан».
   */
  hasSecret: z.boolean(),
  /** Решение человека «включено»; действующая включённость — ниже. */
  isEnabled: z.boolean(),
  /** `isEnabled` и полнота настройки вместе: по нему судит интерфейс. */
  isOperational: z.boolean(),
  /** Код причины из списка выше. Пусто — работает. */
  blockedBy: z.string().nullable(),
  updatedAt: z.string().nullable(),
  updatedByLabel: z.string().nullable(),
});

/**
 * Что можно выбрать в трекере: его проект, доска или колонка.
 *
 * Идентификатор — **строка**, хотя Weeek отдаёт числа: арифметики над ним
 * нет, у второго трекера он может быть не числом, а большое число потеряло
 * бы точность в `number` ещё и молча.
 */
export const trackerTargetSchema = z.object({
  id: z.string().min(1),
  name: z.string(),
});

/**
 * Списки, из которых собирается привязка: «Куда выгружать».
 *
 * Три плоских списка для интерфейса. Адаптер получает их последовательно:
 * `/tm/projects`, затем `/tm/boards?projectId=...` для каждого проекта и
 * `/tm/board-columns?boardId=...` для каждой доски.
 * Родитель назван у доски и колонки: по нему интерфейс и строит каскад.
 *
 * Идут **через нашу ручку**, а не прямым запросом из браузера: токен не
 * покидает сервер (дизайн, 9.3).
 */
export const trackerTargetsSchema = z.object({
  projects: z.array(trackerTargetSchema),
  boards: z.array(trackerTargetSchema.extend({ projectId: z.string().nullable() })),
  columns: z.array(trackerTargetSchema.extend({ boardId: z.string().nullable() })),
});

/**
 * Привязка проекта: куда выгружать его задачи.
 *
 * Все три идентификатора обязательны. Половина привязки — то же
 * угадывание, от которого избавляет сама привязка: «разные проекты —
 * разные доски» (дизайн, 3.5), и задача, положенная «куда-нибудь», нашлась
 * бы не там, где её ищут.
 */
export const trackerBindingUpdateSchema = z
  .object({
    externalProjectId: z.string().trim().min(1).max(100),
    boardId: z.string().trim().min(1).max(100),
    boardColumnId: z.string().trim().min(1).max(100),
  })
  .strict();

/**
 * Привязка проекта в ответе ручки.
 *
 * `tracker` назван, хотя трекер на установку один: строка привязки помнит
 * вид, и ответ, который о нём молчит, пришлось бы переделывать ровно тогда,
 * когда появится второй. Имён проектов и досок здесь нет — они приходят
 * {@link trackerTargetsSchema}, то есть живым запросом в трекер, и хранить
 * их второй копией значило бы показывать имя доски, переименованной месяц
 * назад.
 */
export const trackerBindingSchema = z.object({
  tracker: z.nativeEnum(TrackerKind),
  externalProjectId: z.string(),
  boardId: z.string(),
  boardColumnId: z.string(),
  updatedAt: z.string(),
  updatedByLabel: z.string().nullable(),
});

/**
 * Исход живой проверки связи с трекером.
 *
 * Своя схема рядом с `modelProbeResultSchema`, а не она же: у того `model`
 * обязателен, и трекеру пришлось бы присылать пустую строку — поле, которое
 * ничего не значит, читается как «модель неизвестна». Исходы при этом **те
 * же шесть**: `ModelProbeOutcome` описывает не узел модели, а чужой HTTP, и
 * второй перечень с теми же значениями разошёлся бы с первым.
 *
 * `.strict()` не формальность: исход уходит на экран и в журнал, а в теле
 * чужого ответа бывает и сам токен — в сообщении о неверном заголовке.
 */
export const trackerProbeResultSchema = z
  .object({
    outcome: z.nativeEnum(ModelProbeOutcome),
    /** Код HTTP, если он был. Число — не утечка, тело — утечка. */
    status: z.number().int().nullable(),
    host: z.string().nullable(),
    durationMs: z.number().int().nonnegative(),
  })
  .strict();

/**
 * Трекер со стороны проекта: можно ли выгружать и куда.
 *
 * Отдельная проекция рядом с {@link trackerConnectionSchema}, потому что её
 * читает другой человек: подрядчику с записью на «Роадмап» нужен ответ на
 * «можно ли выгружать» и «куда настроено», а адрес, имя узла и состояние
 * токена принадлежат настройке установки и экрану `/settings`. Отдать здесь
 * `TrackerConnection` значило бы показать чужую настройку тому, кому она не
 * принадлежит, — и показать её при каждом открытии экрана задач.
 *
 * `blockedBy` назван, хотя чинит его не этот человек: без причины кнопка
 * выгрузки была бы выключена молча, а молчание отправляет к администратору
 * с вопросом «почему» вместо «включите токен» (дизайн, 9.2 и C4 плана).
 */
export const projectTrackerSchema = z.object({
  isOperational: z.boolean(),
  blockedBy: z.string().nullable(),
  /** `null` — привязки нет: состояние, а не ошибка. */
  binding: trackerBindingSchema.nullable(),
});

/**
 * Зеркало выгрузки задачи во внешний трекер.
 *
 * **Только зеркало** (решение владельца, дизайн 5): здесь нет ни одного
 * поля, которое что-нибудь закрывает. Чекпоинт закрывает человек, прогресс
 * версии считается только из чекпоинтов, а «закрыта там, открыта здесь» —
 * законное состояние, которое экран показывает биркой. Автоматическое
 * закрытие означало бы, что упавший опрос, снятый токен или переименованная
 * колонка молча останавливают прогресс роадмапа.
 *
 * Своей схемой, а не полями у задачи, по той же причине, по которой это
 * своя таблица (дизайн, 3.3): опрос пишет сюда часто, формулировку правят
 * редко.
 *
 * `.strict()` не формальность: зеркало собирается из ответа чужой системы,
 * и поле «как пришло» унесло бы на экран тело чужого ответа — в нём бывает
 * и сам токен, в сообщении о неверном заголовке.
 */
export const taskExportSchema = z
  .object({
    tracker: z.nativeEnum(TrackerKind),
    /** Идентификатор задачи в трекере: им идут `PUT` и опрос. */
    externalId: z.string(),
    /**
     * Ссылка для человека, и она **не** `task.url`.
     *
     * `task.url` вписал человек, и выгрузка его не перезаписывает (дизайн,
     * 3.1): одно поле на две ссылки означало бы, что первая же выгрузка
     * затёрла заметку, которую человек держал именно там.
     *
     * Обнуляема: формат ссылки Weeek живым токеном не проверен (дизайн,
     * 10.4), и пустое значение честно означает «мы её не знаем», в отличие
     * от собранной по выдуманному шаблону, которая увела бы на `404`.
     */
    externalUrl: z.string().nullable(),
    /** Куда положили: доска из привязки проекта, известна до первого байта. */
    externalBoardId: z.string(),
    /**
     * Где лежит сейчас. Обнуляема, потому что приходит **ответом** трекера,
     * а ответ может колонку не назвать; подставить туда колонку привязки
     * значило бы утверждать, что задачу не двигали, — ровно то, за чем на
     * этот экран и смотрят.
     */
    externalColumnId: z.string().nullable(),
    /** Закрыта ли задача **там**. Здесь не закрывает ничего. */
    isCompleted: z.boolean(),
    exportedAt: z.string(),
    updatedAt: z.string(),
    /**
     * Когда **спрашивали** статус.
     *
     * Пишется при каждом опросе, даже когда ничего не изменилось (дизайн,
     * 3.3): иначе «давно не спрашивали» не отличить от «не менялось» — та
     * же ошибка, что аптайм без пропусков наблюдения. Пусто означает ровно
     * «опроса ещё не было».
     */
    checkedAt: z.string().nullable(),
    /** Код последней неудачи обмена из списка выше; пусто после удачи. */
    failureCode: z.string().nullable(),
  })
  .strict();

/**
 * Сколько задач принимает одна выгрузка.
 *
 * Выгрузка идёт по одному запросу на задачу и последовательно, потому что
 * чужой API считает частоту. Набор без предела оборвался бы по таймауту
 * прокси или браузера, и человек не узнал бы, сколько задач уже уехало, а
 * повтор правил бы в трекере то, что уже уехало.
 *
 * **Срок ответа ручки этим числом не выражается, и прежнее «длина набора и
 * есть время ответа» было неправдой**: пятьдесят обменов по двадцать секунд —
 * это шестнадцать минут в одной ручке. Пределов поэтому два, про разное:
 * здесь — сколько задач человек вправе попросить за раз (и о чём ему говорит
 * форма **до** нажатия), а срок ответа держит бюджет времени в службе
 * (`EXPORT_BATCH_BUDGET_MS`), который недошедшим задачам отвечает исходом
 * `skipped`. Контракту бюджет не принадлежит: это свойство нашего обмена, а
 * не договор о теле запроса.
 *
 * Предел ниже, чем у черновика саммари
 * (`MAX_SUMMARY_TASKS`, 200), и это не описка: там двести строк пишутся в
 * свою базу одной транзакцией, здесь каждая — поход в чужую сеть.
 */
export const MAX_TASK_EXPORT_BATCH = 50;

/**
 * Что выгружать: набор задач реестра.
 *
 * Одна ручка на одну и на много задач — набор из одного элемента и есть
 * одна задача (план, C2). Вторая ручка «выгрузить одну» повторяла бы
 * порядок действий, в котором запись в журнал обязана идти до первого
 * байта, а повторённый порядок расходится.
 *
 * `.strict()`: доска и колонка приходят привязкой проекта, а не телом —
 * иначе субъект с записью на «Роадмап» положил бы задачу на чужую доску,
 * минуя настройку (дизайн, 3.5). Формулировок в теле нет по той же
 * причине: наружу уходит содержимое реестра, а присланная строка уехала бы
 * в трекер, не совпав ни с одной задачей в журнале.
 *
 * Новых кодов отказа у выгрузки не появилось: четыре кода обмена пакета B
 * отвечают на все её вопросы — трекер не настроен, доска не привязана, не
 * ответил, отказал, — а «задачи нет» это `TASK_NOT_FOUND`, то есть `404`,
 * как везде.
 */
export const taskExportRequestSchema = z
  .object({
    taskIds: z.array(z.string().uuid()).min(1).max(MAX_TASK_EXPORT_BATCH),
  })
  .strict();

/**
 * Что случилось с одной задачей набора: строка итога выгрузки.
 *
 * Ручка выгрузки отвечает **`200` с итогом на каждую задачу**, а не одним
 * кодом HTTP, и это решение, а не удобство: исход у набора не один. `502` на
 * наборе, где три задачи уехали, сказал бы «ничего не вышло» и заставил бы
 * человека нажать повтор, то есть править в трекере то, что уже правильно, —
 * а повтор идёт `PUT`, то есть не бесплатен. Кодом HTTP остаются только
 * отказы, которые относятся ко **всему** набору и случаются до первого байта
 * наружу: нет права (`404`/`403`), нет привязки или подключения (`409`), нет
 * задачи (`404`).
 *
 * Отсюда же и `failureCode` строкой итога: экран показывает «Обмен не
 * удался» биркой у задачи (дизайн, 9.2), а бирка рисуется из данных, а не из
 * кода ответа.
 *
 * `.strict()` не формальность: исход собирается вокруг ответа чужой системы,
 * и поле «как пришло» унесло бы на экран тело чужого ответа — в нём бывает и
 * эхо присланной формулировки, и сам токен.
 */
export const taskExportResultSchema = z
  .object({
    taskId: z.string().uuid(),
    outcome: z.nativeEnum(TaskExportOutcome),
    /** Код обмена при неудаче; у остальных исходов пусто. */
    failureCode: z.string().nullable(),
    /**
     * Зеркало после обмена; `null` — выгрузки у задачи так и нет.
     *
     * У неудачной первой выгрузки пусто намеренно: строка выгрузки
     * заводится только после удачного создания задачи в трекере, и строка с
     * одним кодом отказа означала бы «задача там есть, но мы не знаем,
     * где», — то есть врала бы экрану о состоявшейся выгрузке.
     */
    export: taskExportSchema.nullable(),
  })
  .strict();

