import { z } from 'zod';

/**
 * Название тега: «Web», «Product», «Внутренний».
 *
 * Короткое намеренно: тег — верхнеуровневая метка для фильтра сводки,
 * а не описание. Длинному место в назначении проекта.
 */
export const tagLabelSchema = z.string().trim().min(1).max(40);

/**
 * Приводит название к форме, по которой теги сопоставляются.
 *
 * Один источник нормализации на обе стороны: сервер хранит её в колонке
 * `slug` под уникальным ключом, веб по ней же сравнивает чипы фильтра.
 * Две реализации разошлись бы, и в реестре появился бы второй «web».
 *
 * Регистр гасится, внутренние пробелы сводятся к одному. Сам `label`
 * остаётся таким, как его написали: именно он виден в сводке.
 */
export function tagSlug(label: string): string {
  return label.trim().toLowerCase().replace(/\s+/g, ' ');
}

/**
 * Тег проекта: верхнеуровневая метка, общая на все проекты.
 *
 * Межпроектный реестр, в отличие от платформы: «Web» одного проекта и
 * «Web» другого — один и тот же тег, иначе фильтровать сводку по нему
 * было бы нечем. Своего экрана у реестра нет — он наполняется самим
 * фактом того, что тег кому-то приписали, как корневой домен заводится
 * появлением адреса.
 */
export const tagSchema = z.object({
  id: z.string().uuid(),
  /** Форма сопоставления: по ней работает фильтр и уникальность реестра. */
  slug: z.string(),
  /** Что видно в сводке. */
  label: z.string(),
});

/**
 * Набор тегов проекта: правится целиком.
 *
 * Целиком, а не мутацией на тег, в отличие от платформ: за тегом ничего
 * не стоит — ни выпусков, ни привязок к окружению, — и удалять его
 * отдельной ручкой незачем. Пустой набор означает «снять все», и
 * отличается от отсутствия поля при создании проекта.
 *
 * Повторы отвергаются по нормализованной форме: «Web» и «web» легли бы
 * в одну строку связи, и вторая вставка упёрлась бы в составной ключ.
 */
export const tagSetSchema = z
  .object({
    labels: z
      .array(tagLabelSchema)
      .max(20)
      .refine(
        (labels) => new Set(labels.map(tagSlug)).size === labels.length,
        'Теги повторяются',
      ),
  })
  .strict();

/** Тег проекта. */
export type Tag = z.infer<typeof tagSchema>;

/** Набор тегов проекта. */
export type TagSet = z.infer<typeof tagSetSchema>;
