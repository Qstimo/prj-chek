/** Пропсы поля доменов. */
export interface IProps {
  value: string[];
  onChange: (domains: string[]) => void;
  /**
   * Известные адреса реестра для подсказки.
   *
   * Отсутствие списка означает, что реестр этому человеку не виден: поле
   * остаётся обычным вводом текста. Показать список подрядчику значило бы
   * раскрыть чужие адреса, а через них — существование чужих проектов.
   * Пустой список — это видимый, но пустой реестр: подсказка работает.
   */
  knownDomains?: string[];
}
