/**
 * Раздел проекта, в котором мы находимся.
 *
 * Разбор по префиксу, а не точное равенство: у разделов появились вложенные
 * адреса (отчёт по релизу лежит внутри роадмапа), и при точном сравнении
 * такая страница оставалась без раздела — ни пометки текущего, ни пути
 * назад в крошках.
 *
 * Граница сегмента обязательна: без неё «/roadmapped» считался бы вложенным
 * адресом роадмапа.
 *
 * «Инфо» — исключение: её адрес и есть адрес проекта, и по префиксу она
 * совпала бы сразу с каждым вложенным разделом. Для неё остаётся точное
 * равенство.
 */
export function isSectionActive(pathname: string, href: string, path: string): boolean {
  if (path === '') {
    return pathname === href;
  }

  return pathname === href || pathname.startsWith(`${href}/`);
}
