/** Пропсы поля ввода. */
export interface IProps {
  id: string;
  label: string;
  value: string;
  onChange: (value: string) => void;
  /** Многострочное поле вместо однострочного. */
  multiline?: boolean;
  /**
   * Сколько строк видно у многострочного поля. Умолчание — три.
   *
   * Настройкой, а не одним числом на все места: в трёх строках правят
   * описание, а текст созвона — это страницы, и поле в три строки
   * заставляет прокручивать то, что человек обязан перечитать целиком
   * прежде, чем отправить.
   */
  rows?: number;
  /** Тип поля. Игнорируется для многострочного. */
  type?: 'text' | 'email' | 'date';
}
