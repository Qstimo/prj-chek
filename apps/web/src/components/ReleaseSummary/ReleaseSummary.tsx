import { SummaryRow } from './SummaryRow';
import type { IProps } from './types';

/**
 * Сводка релизов над диаграммой роадмапа.
 *
 * Презентационный компонент, данные только пропами: тот же экземпляр
 * работает на внутреннем экране (из кэша TanStack Query) и на публичной
 * странице, которая получает роадмап пропом от серверной страницы
 * и TanStack Query не поднимает.
 *
 * Порядок строк не меняется: сервер уже упорядочил их по позиции
 * платформы, и вторая сортировка здесь разошлась бы с ним.
 */
export function ReleaseSummary({ summary }: IProps) {
  if (summary.length === 0) {
    return null;
  }

  // Колонка имён — по самому длинному имени, а не по заданной ширине.
  // Фиксированный максимум (`8rem`/`10rem`) сетка считает определённым и
  // занимает целиком независимо от содержимого: у «API» между именем и
  // плашкой зияла половина колонки. `auto` берёт ширину по содержимому и,
  // в отличие от `max-content`, ужимается, когда места мало, — на телефоне
  // длинное имя не выдавит плашку за край.
  //
  // Нижняя граница оставлена: без неё колонка схлопывается до самого
  // короткого имени, и плашки встают вплотную к тексту.
  //
  // У колонки плашек своя нижняя граница: без неё длинное имя на телефоне
  // забирало ширину себе, и плашка ломалась пополам, а дата падала под
  // неё. С границей сжимается имя — оно переносится, на то у `dt` и стоит
  // `break-words`, — а плашка остаётся читаемой строкой.
  return (
    <dl className="grid grid-cols-[minmax(5rem,auto)_minmax(8rem,1fr)] items-start gap-x-4 gap-y-3">
      {summary.map((row) => (
        <SummaryRow key={row.platform.id} row={row} />
      ))}
    </dl>
  );
}
