/** Пропсы файлового поля. */
export interface IProps {
  /** Идентификатор поля: с ним связана видимая подпись. */
  id: string;
  /** Видимая подпись поля. */
  label: string;
  /** Что предложить в диалоге выбора: `accept` настоящего поля. */
  accept: string;
  /** Подпись под областью: что принимается и какие пределы. */
  hint: string;
  /**
   * Файл выбран кнопкой или брошен на область.
   *
   * Один обработчик на оба способа: проверки у файла одни и те же, и
   * вторая их копия под бросок разошлась бы с первой (дизайн расшифровки,
   * 8.2 — порядок проверок обязателен).
   */
  onFile: (file: File) => void;
  /** Выбор выключен: идёт отправка. */
  isDisabled?: boolean;
  /**
   * Что выбрано — словами, **без имени файла**.
   *
   * Имена файлов на машинах людей нередко говорят больше содержимого, и
   * ни показывать, ни отправлять их мы не хотим; формат и размер при этом
   * человеку нужны: без них выбор ничем не отличается от отсутствия
   * выбора.
   */
  picked?: string;
}
