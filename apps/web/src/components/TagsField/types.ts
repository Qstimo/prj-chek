/** Пропсы поля тегов. */
export interface IProps {
  /** Названия тегов проекта в том порядке, в каком их показывать. */
  tags: string[];
  /**
   * Новый набор целиком, а не «добавить» и «убрать» по отдельности.
   *
   * Набор правится целиком и на сервере — одной ручкой `PUT`, — и две
   * половинки здесь разошлись бы с единственным путём записи: панель
   * создания складывала бы их в своё состояние, панель правки звала бы
   * мутацию дважды на одно действие.
   */
  onChange: (tags: string[]) => void;
  /**
   * Словарь: чем помечают в видимых паспортах.
   *
   * Подсказки, а не каталог: тег остаётся свободным. Нужны против
   * расхождения словаря — рядом с «Web» иначе появляется «Вэб».
   */
  suggestions?: string[];
}
