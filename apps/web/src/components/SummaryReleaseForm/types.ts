import type { RoadmapVersionState, SummaryRelease } from '@cairn/shared';

/** Значения трёх полей формы релиза. */
export interface IReleaseFormValues {
  label: string;
  state: RoadmapVersionState;
  plannedDate: string;
}

/**
 * Версия-получатель в выборе цели: только то, что нужно выбору.
 *
 * Не `RoadmapVersionMetadata`: прогресс, даты и признак расхождения форме
 * релиза не нужны, а проп, который принимает лишнее, со следующей правкой
 * начнут этим лишним кормить.
 */
export interface IReleaseTargetVersion {
  id: string;
  label: string;
}

/** Пропсы формы релиза из саммари. */
export interface IProps {
  /**
   * Подсказка обозначения, вычисленная сервером.
   *
   * `null` значит «подставлять нечего»: версий нет, в их обозначениях нет
   * цифр, или у субъекта нет выдачи на роадмап.
   */
  suggestedLabel: string | null;
  /** Сколько отмеченных задач станут незакрытыми чекпоинтами. */
  taskCount: number;
  /**
   * Версии проекта для цели «существующая версия».
   *
   * Приходят **существующим запросом роадмапа**, а не новым полем детали
   * саммари: кнопка релиза и так доступна только при `Роадмап ≥ запись`,
   * а значит чтение версий субъекту открыто (дизайн, 4.5). Пустой список
   * означает «выбирать нечего» — выбора цели тогда нет вовсе.
   */
  versions?: IReleaseTargetVersion[];
  /**
   * Цель релиза целиком: либо новая версия, либо идентификатор готовой.
   *
   * Размеченное объединение из контракта, а не два обработчика: тело
   * ручки принимает ровно его, и собирать его из двух половин на
   * вызывающей стороне значило бы завести второе правило формы.
   *
   * `releasedDate` внутри `new` не бывает никогда — даже как `null`
   * (дизайн конструктора, раздел 7.5).
   */
  onSubmit: (target: SummaryRelease['target']) => void;
  /** Роадмап проекта опубликован: чекпоинты попадут в публичную выдачу. */
  isRoadmapPublic?: boolean;
  /** Отправка в процессе. */
  isSubmitting?: boolean;
  /** Отказ сервера. */
  error?: string;
}
