/** Сколько чекпоинтов создастся: число названо до нажатия, а не после. */
export function checkpointsNoteOf(count: number): string {
  return `Версия будет создана с ${pluralize(count, 'незакрытым чекпоинтом', 'незакрытыми чекпоинтами', 'незакрытыми чекпоинтами')}.`;
}

/**
 * То же число, но у существующей версии — и с её обозначением.
 *
 * «Версия будет создана» здесь соврало бы: она уже есть, и задачи к ней
 * добавляются. Обозначение названо в той же фразе, а не отдельной
 * строкой: оно отвечает на тот же вопрос «куда уедет отмеченное».
 */
export function appendNoteOf(count: number, label: string): string {
  return `В версию ${label} добавятся ${pluralize(count, 'незакрытый чекпоинт', 'незакрытых чекпоинта', 'незакрытых чекпоинтов')}.`;
}
