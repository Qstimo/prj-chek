/** Пропсы панели действий формы. */
export interface IProps {
  /** Подпись кнопки отправки. */
  submitLabel: string;
  /** Можно ли отправлять: пустое обязательное поле блокирует кнопку. */
  canSubmit: boolean;
  /** Отправка в процессе: подпись меняется на «Сохранение…». */
  isSubmitting?: boolean;
  /**
   * Возврат без сохранения.
   *
   * Отсутствие означает, что возвращаться некуда: форму создания
   * закрывает сама панель.
   */
  onCancel?: () => void;
  /** Отказ сервера: показывается рядом с кнопкой, а не в конце формы. */
  error?: string;
  /**
   * Прилипает ли полоса к низу панели.
   *
   * По умолчанию да: форма занимает панель целиком. Вложенная форма
   * (правка чекпоинта внутри панели версии) прилипать не должна — две
   * полосы спорили бы за одно место внизу.
   */
  isSticky?: boolean;
}
