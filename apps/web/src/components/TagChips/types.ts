/** Пропсы чипов тегов. */
export interface IProps {
  /**
   * Теги в минимальной форме: чипу нужны только название и ключ.
   *
   * Не `Tag`: потребители приходят с разными наборами полей — строка
   * сводки с полным тегом, фильтр со своими подсчётами. Требовать полную
   * форму значило бы приводить данные к ней в каждом месте.
   */
  tags: { slug: string; label: string }[];
}
