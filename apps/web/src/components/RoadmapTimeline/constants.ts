import type { TimelineForm } from './types';

/** Шаг оси в единицах разметки: он же ширина места версии в ленте. */
export const STEP = 96;

/** Высота полосы с отметкой в единицах разметки. */
export const MARK_HEIGHT = 56;

/** Геометрия отметки внутри шага. */
export const MARK = { cx: STEP / 2, cy: 28, radius: 16 } as const;

/**
 * Высота места версии в серпантине.
 *
 * Задана, а не взята у содержимого: колено соединяет центры отметок двух
 * строк, и нарисовать его можно только зная расстояние между строками.
 * Величина набрана по содержимому: отметка (56) плюс обозначение (16),
 * плюс пояснение с датой в две строки (32), плюс счёт чекпоинтов (16).
 */
export const SLOT_HEIGHT = 120;

/** Высота строки поворота между двумя строками версий. */
export const KNEE_HEIGHT = 24;

/** Ширина крайних столбцов сетки: по ним идёт вертикаль колена. */
export const TURN_WIDTH = 24;

/** Радиус закругления колена. */
export const KNEE_RADIUS = 8;

/**
 * Столбцов в строке серпантина, пока ширина не измерена.
 *
 * Умолчание нарочно скромное: до первого измерения лучше показать строку
 * короче места, чем уехать в прокрутку. Шесть столбцов — 624 px оси плюс
 * два поворота, то есть любая полоса от телефона в ландшафте и шире.
 */
export const DEFAULT_COLUMNS = 6;

/** Сколько последних версий показывает фильтр «последние N». */
export const DEFAULT_LAST = 10;

/**
 * Пределы заполненности отметки.
 *
 * Заполненность зажимается с обеих сторон, и это не огрубление, а защита от
 * прямой лжи. При трёх сотнях чекпоинтов честная доля даёт `1/347` — сектор
 * тоньше пикселя, неотличимый от «не начинали», — и `346/347`, неотличимое
 * от полного круга «выпущено». Зажим говорит правду о состоянии («начали» /
 * «ещё не всё»), а точное число стоит рядом словами.
 */
export const FILL_MIN = 0.08;

/** Верхний предел заполненности. См. {@link FILL_MIN}. */
export const FILL_MAX = 0.92;

/**
 * Сколько версий лента показывает в одну строку.
 *
 * Расчёт, а не круглое число: шаг постоянный и равен 96 px, внутренний
 * экран даёт под содержимое 976 px (`max-w-5xl` минус `px-6`), значит
 * `10 × 96 = 960 ≤ 976` — последнее количество, умещающееся целиком.
 * Дальше умолчание — серпантин: там строку считает измеренная ширина
 * места, а не этот порог (на публичной странице места 720 px).
 */
export const STRIP_MAX_VERSIONS = 10;

/**
 * Сколько строк списка показывается до раскрытия.
 *
 * Окно режет узлы разметки, а не данные: ответ сервера приходит целиком в
 * любом случае. Смысл окна — не держать в документе сотню кнопок, через
 * которые придётся проходить табуляцией.
 */
export const LIST_WINDOW = 20;

/** Размер окна по умолчанию для каждой укладки. */
export const WINDOW_SIZES: Record<TimelineForm, number> = {
  strip: STRIP_MAX_VERSIONS,
  serpentine: DEFAULT_LAST,
  list: LIST_WINDOW,
};

/** Названия укладок в переключателе. */
export const FORM_LABELS: Record<TimelineForm, string> = {
  strip: 'Полоса',
  serpentine: 'Серпантин',
  list: 'Список',
};

/** Классы обёртки для каждой укладки. */
export const WRAPPER_CLASSES: Record<TimelineForm, string> = {
  // Лента прокручивается вбок, когда не вмещается; короткая — по центру.
  strip: 'overflow-x-auto',
  // Серпантин считает строку по измеренной ширине этой самой обёртки, но
  // прокрутка остаётся запасным выходом: до первого измерения строка
  // берётся по умолчанию, и оно может не совпасть с местом.
  serpentine: 'overflow-x-auto',
  list: '',
};

/** Классы ряда элементов для каждой укладки. */
export const ROW_CLASSES: Record<TimelineForm, string> = {
  strip: 'flex w-max min-w-full justify-center',
  // Сетка, а не перенос строк: направление строк чередуется, и место
  // каждой версии задаётся столбцом явно — переносом этого не выразить.
  serpentine: 'grid w-max min-w-full justify-center',
  list: 'grid gap-1',
};

/**
 * Классы места в ряду.
 *
 * Ширину держит место, а не содержимое, и задаётся она не классом, а
 * шагом {@link STEP}: класс `w-24` совпадал с ним только при корневом
 * шрифте 16 px, то есть шаг был задан дважды и расходился от настроек
 * браузера.
 */
export const SLOT_CLASSES: Record<TimelineForm, string> = {
  strip: 'shrink-0',
  // Высота места в серпантине задана, и содержимое выше неё обрезается:
  // разъехавшиеся строки увели бы концы колена от центров отметок.
  serpentine: 'overflow-hidden',
  list: '',
};

/** Классы содержимого элемента для каждой укладки. */
export const ITEM_CLASSES: Record<TimelineForm, string> = {
  strip: 'rounded-md',
  serpentine: 'h-full rounded-md',
  // Строка списка — цель нажатия в 44 px при любом числе версий.
  list: 'flex min-h-11 items-center gap-3 rounded-md px-2 py-1.5 text-left',
};
