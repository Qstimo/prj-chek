import type { TimelineForm } from './types';

/** Шаг оси в единицах разметки: он же ширина отметки в лентовой укладке. */
export const STEP = 96;

/** Высота полосы с отметкой в единицах разметки. */
export const MARK_HEIGHT = 56;

/** Геометрия отметки внутри шага. */
export const MARK = { cx: STEP / 2, cy: 28, radius: 16 } as const;

/**
 * Пределы заполненности отметки.
 *
 * Заполненность зажимается с обеих сторон, и это не огрубление, а защита от
 * прямой лжи. При трёх сотнях чекпоинтов честная доля даёт `1/347` — сектор
 * тоньше пикселя, неотличимый от «не начинали», — и `346/347`, неотличимое
 * от полного круга «выпущено». Зажим говорит правду о состоянии («начали» /
 * «ещё не всё»), а точное число стоит рядом словами.
 */
export const FILL_MIN = 0.08;

/** Верхний предел заполненности. См. {@link FILL_MIN}. */
export const FILL_MAX = 0.92;

/**
 * Сколько версий лента показывает, не превращаясь в список.
 *
 * Расчёт, а не круглое число: шаг постоянный и равен 96 px, внутренний
 * экран даёт под содержимое 976 px (`max-w-5xl` минус `px-6`), значит
 * `10 × 96 = 960 ≤ 976` — последнее количество, умещающееся целиком. На
 * публичной странице поле уже (`max-w-3xl p-6` = 720 px), и там с восьмой
 * версии работает горизонтальная прокрутка ленты.
 */
export const STRIP_MAX_VERSIONS = 10;

/**
 * Сколько строк списка показывается до раскрытия.
 *
 * Окно режет узлы разметки, а не данные: ответ сервера приходит целиком в
 * любом случае. Смысл окна — не держать в документе сотню кнопок, через
 * которые придётся проходить табуляцией.
 */
export const LIST_WINDOW = 20;

/** Классы обёртки для каждой укладки. */
export const WRAPPER_CLASSES: Record<TimelineForm, string> = {
  // Лента прокручивается вбок, когда не вмещается; короткая — по центру.
  strip: 'overflow-x-auto',
  list: '',
};

/** Классы ряда элементов для каждой укладки. */
export const ROW_CLASSES: Record<TimelineForm, string> = {
  strip: 'flex w-max min-w-full justify-center',
  list: 'grid gap-1',
};

/**
 * Классы места в ряду.
 *
 * Ширину держит место, а не содержимое: шаг ленты постоянен и равен 96 px,
 * и это ровно та величина, которую прежний `flex-1` отдавал на откуп числу
 * версий, схлопывая колонки в точки.
 */
export const SLOT_CLASSES: Record<TimelineForm, string> = {
  strip: 'w-24 shrink-0',
  list: '',
};

/** Классы содержимого элемента для каждой укладки. */
export const ITEM_CLASSES: Record<TimelineForm, string> = {
  strip: 'rounded-md',
  // Строка списка — цель нажатия в 44 px при любом числе версий.
  list: 'flex min-h-11 items-center gap-3 rounded-md px-2 py-1.5 text-left',
};
