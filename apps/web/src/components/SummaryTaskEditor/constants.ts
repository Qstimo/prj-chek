/** Счёт отмеченных: ноль показывается тоже — полоса не должна прыгать. */
export function selectedNoteOf(count: number): string {
  return `Отмечено: ${count}`;
}

/** Потеря названа числом до нажатия, а не после (дизайн, 4.3). */
export function deleteQuestionOf(count: number): string {
  return `Из черновика будут удалены ${pluralize(count, 'задача', 'задачи', 'задач')}. Восстановить их будет нечем: в архив они не попадут.`;
}
