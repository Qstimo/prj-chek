import type { Platform, SummaryTask, SummaryTasksReplace } from '@cairn/shared';

/**
 * Строка черновика в памяти редактора.
 *
 * `id` отсутствует у строки, набранной здесь и ещё не сохранённой:
 * именно так её отличает сервер. `key` нужен только React — у новых
 * строк нет ничего устойчивого, а индекс при перестановках переиспользовал
 * бы состояние чужого поля.
 */
export interface IDraftTask {
  key: string;
  id?: string;
  title: string;
  /** Пришла от модели: строка несёт метку «предложено моделью». */
  isFromModel: boolean;
  /**
   * Адрес задачи во внешнем трекере.
   *
   * В памяти — строка, а не `string | null`: пустая означает «ссылки
   * нет» и уезжает как `null`, а `null` в поле ввода пришлось бы
   * отличать от пустой строки у самого поля.
   */
  url: string;
  /** Теги платформ. Только те, что есть в переданном списке платформ. */
  platformIds: string[];
}

/**
 * Действия над отмеченными задачами.
 *
 * Одним объектом, а не тремя пропсами: они приходят вместе и отсутствуют
 * вместе — без них у редактора нет и отметок, потому что отметка
 * существует ради следующего действия и сама по себе ничего не значит.
 *
 * Идентификаторы, а не строки черновика: ручки состояния принимают
 * `taskIds`, и порядок чекпоинтов задаёт `position` в базе, а не порядок
 * отметок (дизайн, 3.6).
 */
export interface ISelectionActions {
  /** Отмеченные уезжают в версию: панель релиза открывает контейнер. */
  onRelease: (taskIds: string[]) => void;
  onArchive: (taskIds: string[]) => void;
  /** Подтверждение спрашивает сам редактор: число знает только он. */
  onDelete: (taskIds: string[]) => void;
  /**
   * Почему выключен **релиз**, или `undefined` — он доступен.
   *
   * Только релиз: архив и удаление — та же «Хроника ≥ запись», что
   * правка черновика, и выдача на роадмап их не касается (дизайн, 3.3).
   */
  releaseBlockedNote?: string;
  /** Действие в полёте: второе нажатие ушло бы вторым запросом. */
  isBusy?: boolean;
}

/** Пропсы одной карточки черновика. */
export interface IRowProps {
  task: IDraftTask;
  /** Первая карточка не поднимается, последняя не опускается. */
  isFirst: boolean;
  isLast: boolean;
  /**
   * Карточка отмечена; `undefined` — отметок нет вовсе.
   *
   * Признак и обработчик приходят парой: показывать отметку, которую
   * нечем переключить, незачем.
   */
  isSelected?: boolean;
  onSelect?: (isSelected: boolean) => void;
  /** Поставить фокус при появлении: только у карточки, добавленной руками. */
  shouldFocus: boolean;
  /** Платформы проекта для чипов. Пустой список — чипов нет вовсе. */
  platforms: Platform[];
  onChange: (title: string) => void;
  onUrlChange: (url: string) => void;
  onPlatformsChange: (platformIds: string[]) => void;
  /** Объяснение негодного адреса; у годного и пустого его нет. */
  urlError?: string;
  onMove: (step: number) => void;
  onRemove: () => void;
}

/**
 * Пропсы нижней части карточки.
 *
 * Подмножество пропсов карточки, а не свой набор: это часть той же
 * карточки, и второе определение тех же полей разошлось бы с первым.
 */
export type IDetailsProps = Pick<
  IRowProps,
  'task' | 'platforms' | 'onUrlChange' | 'onPlatformsChange' | 'urlError'
>;

/** Пропсы редактора черновика. */
export interface IProps {
  /** Загруженный набор: от него считается `isDirty`. */
  tasks: SummaryTask[];
  /**
   * Платформы проекта для чипов тегов — из детали саммари и ниоткуда
   * больше: она отдаёт их под `Roadmap ≥ metadata`.
   *
   * Обязателен намеренно, а не `?: []`: забытый проп означал бы «тегов
   * не видно», а невидимых тегов редактор не отправляет — правка
   * формулировки молча оставляла бы теги прежними там, где человек их
   * правил. Пустой список передаётся явно и означает «показывать
   * нечего».
   */
  platforms: Platform[];
  /** Сохранение целиком: порядок задаёт порядок массива. */
  onSave: (input: SummaryTasksReplace) => void;
  /**
   * Действия над выбором; без них отметок нет вовсе.
   *
   * Необязательны намеренно: редактор умеет работать и как чистый
   * редактор черновика — так он и вызывается там, где над выбором делать
   * нечего.
   */
  actions?: ISelectionActions;
  /**
   * Есть несохранённые правки.
   *
   * Наружу, потому что несохранённое — повод не только для подписи у
   * кнопки: следующий шаг потока читает черновик из базы, а уход со
   * страницы обязан предупредить, и то и другое живёт на контейнере.
   */
  onDirtyChange?: (isDirty: boolean) => void;
  /** Сохранение в процессе. */
  isSaving?: boolean;
  /** Отказ сервера рядом с кнопкой. */
  error?: string;
}
