import type { ReactNode } from 'react';

/** Ширина выезжающей панели. */
export enum DrawerWidth {
  /** Форма в несколько полей. */
  Default = 'default',
  /** Панель с длинными формулировками — роадмап. */
  Wide = 'wide',
  /** Форма на половину экрана: паспорт проекта, окружение. */
  Half = 'half',
}

/** Пропсы выезжающей панели. */
export interface IProps {
  isOpen: boolean;
  onClose: () => void;
  /** Заголовок — он же имя диалога для читалок. */
  title: string;
  /** Ширина; по умолчанию узкая. */
  width?: DrawerWidth;
  /**
   * Органы управления в шапке — рядом с закрытием.
   *
   * Шапка прилипшая, поэтому действие, относящееся ко всей панели
   * (сохранение черновика), остаётся на виду при любой прокрутке.
   */
  actions?: ReactNode;
  children: ReactNode;
}
