import { ModelProbeOutcome } from '@cairn/shared';

/**
 * Фразы по исходам проверки связи — собирает **интерфейс**, а не сервер.
 *
 * С сервера приходят исход, код HTTP числом, имя узла, имя модели и
 * длительность; тела чужого ответа не приходит ни целиком, ни фрагментом
 * (дизайн, 8.3). Значит фраза обязана собираться здесь, и шесть фраз — не
 * вежливость: по исходам человек делает **разное**, а один общий «не
 * вышло» отправил бы его делать не то.
 *
 * Строка `not_found` стоит отдельного слова: лишний или недостающий `/v1`
 * в адресе — ошибка, на которой спотыкаются все, и подсказать её прямо
 * дешевле, чем отвечать на неё в переписке.
 */
export const OUTCOME_MESSAGES: Record<ModelProbeOutcome, string> = {
  [ModelProbeOutcome.Ok]: 'Связь есть: узел ответил, модель принята',
  [ModelProbeOutcome.Unauthorized]: 'Ключ не принят. Проверьте ключ у провайдера',
  [ModelProbeOutcome.NotFound]:
    'Ручки нет. Проверьте адрес — обычно в нём лишний или недостающий /v1',
  [ModelProbeOutcome.BadRequest]:
    'Узел отказался от запроса: обычно это неверное имя модели или параметр, которого он не принимает',
  [ModelProbeOutcome.Unavailable]: 'Узел не ответил. Попробуйте ещё раз',
  [ModelProbeOutcome.BadResponse]: 'Узел ответил, но не тем: разобрать ответ не удалось',
};

/** Исход, после которого настройку чинить не нужно. */
export const OK_OUTCOME = ModelProbeOutcome.Ok;
