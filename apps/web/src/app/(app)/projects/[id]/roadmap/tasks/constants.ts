/**
 * Фраза отказа обмена: незнакомый код показывается как есть.
 *
 * Одно место на все три, где отказ обмена показывается, — бирка зеркала,
 * бирка только что неудавшейся попытки и баннер экрана. Второй экземпляр
 * этого выражения разошёлся бы с первым ровно на незнакомом коде, то есть
 * там, где подставить вместо кода общую фразу хуже всего: код ищется в
 * журнале и в логе, «обмен не удался» без кода — нигде.
 */
export function exportFailureTextOf(code: string): string {
  return EXPORT_TEXTS.failed(EXPORT_FAILURES[code] ?? code);
}

/**
 * Фраза отказа по коду: сначала коды задачи, потом коды обмена.
 *
 * Одна функция на обе карты, а не два места разбора в экране: отказ
 * приходит одним и тем же путём — телом ответа с кодом, — и вторая ветка
 * разбора добавила бы третий исход «код есть, фразы нет» молчанием.
 */
export function taskFailureTextOf(code: string): string | undefined {
  if (EXPORT_FAILURES[code] !== undefined) {
    return exportFailureTextOf(code);
  }

  return TASK_FAILURES[code];
}

