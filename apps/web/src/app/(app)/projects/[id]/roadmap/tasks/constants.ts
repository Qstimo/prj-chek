/**
 * Отказы обмена при выгрузке — словами и по действию.
 *
 * Своя карта, а не `BINDING_FAILURES` соседнего экрана: там те же коды
 * отвечают на «почему пуст список досок», здесь — на «почему задача не
 * уехала», и общий текст объяснил бы одному из двух не то. Незнакомый код
 * показывается как есть: он ищется в журнале и в логе, а «обмен не удался»
 * без кода не ищется нигде.
 */
