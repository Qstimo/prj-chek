import { describe, expect, it } from 'vitest';

import { limitOf, megabytesOf } from './format-bytes';

describe('размер записи для экрана', () => {
  it('полугигабайтное видео называется мегабайтами', () => {
    expect(megabytesOf(566_231_040)).toBe('540 МБ');
  });

  it('дорожка — тоже', () => {
    // Два числа в одной строке «540 МБ → 11 МБ» считаются одинаково:
    // иначе одно и то же округление разошлось бы между ними.
    expect(megabytesOf(11_534_336)).toBe('11 МБ');
  });

  it('округляет, а не отбрасывает', () => {
    // 9,54 МиБ — это «10 МБ»: отброшенная дробь показала бы девять там,
    // где файловый менеджер показывает десять.
    expect(megabytesOf(10_000_000)).toBe('10 МБ');
  });

  it('файл меньше мегабайта называется словами, а не нулём', () => {
    // «0 МБ» прочиталось бы как «ничего не загрузилось».
    expect(megabytesOf(100_000)).toBe('меньше 1 МБ');
  });
});

describe('предел размера для подписи', () => {
  it('два гигабайта называются гигабайтами', () => {
    // «2048 МБ» никто не читает как два гигабайта, а предел загрузки
    // человек сверяет с тем, что показывает его файловый менеджер.
    expect(limitOf(2_147_483_648)).toBe('2 ГБ');
  });

  it('предел отправки остаётся в мегабайтах', () => {
    // Сорок мегабайт гигабайтами не выражаются вовсе.
    expect(limitOf(41_943_040)).toBe('40 МБ');
  });

  it('предел меньше мегабайта называется килобайтами, а не словами', () => {
    // «Файл больше меньше 1 МБ» — фраза, которая не читается вовсе, а
    // такой предел у текстового файла саммари как раз и есть.
    expect(limitOf(786_432)).toBe('768 КБ');
  });
});
