/** Сколько байт в мегабайте: двоичный, как его считают файловые менеджеры. */
const MEGABYTE = 1024 * 1024;

/**
 * Размер записи в мегабайтах — одной фразой для экрана.
 *
 * Общая для очереди расшифровок и плеера саммари: в обоих местах
 * человеку показывают **те же** два числа — что загрузили и что уйдёт
 * наружу, — и два способа их округлить разошлись бы на одном и том же
 * файле.
 *
 * Округление до целого намеренно: точность до байта здесь не значит
 * ничего, а «540 МБ → 11 МБ» читается с одного взгляда. Файл меньше
 * мегабайта называется словами, а не нулём: «0 МБ» прочиталось бы как
 * «ничего не загрузилось».
 */
export function megabytesOf(bytes: number): string {
  if (bytes < MEGABYTE) {
    return 'меньше 1 МБ';
  }

  return `${Math.round(bytes / MEGABYTE)} МБ`;
}

/**
 * Предел размера для подписи: гигабайты, мегабайты или килобайты.
 *
 * Отдельно от {@link megabytesOf}, потому что предел человек сверяет с тем,
 * что показывает его файловый менеджер, а «2048 МБ» никто не читает как два
 * гигабайта. Размеры самих записей, наоборот, стоят рядом в одной строке
 * («540 МБ → 11 МБ»), и две разные единицы в ней сравнивались бы глазами
 * хуже, чем два числа.
 *
 * Предел меньше мегабайта называется **килобайтами**, а не словами: у
 * размера «меньше 1 МБ» — честный ответ на вопрос «много ли это», а у
 * предела тот же оборот даёт «файл больше меньше 1 МБ», то есть фразу,
 * которая не читается вовсе. Такой предел есть у текстового файла саммари.
 */
export function limitOf(bytes: number): string {
  if (bytes >= 1024 * MEGABYTE) {
    return `${Math.round(bytes / 1024 / MEGABYTE)} ГБ`;
  }

  if (bytes < MEGABYTE) {
    return `${Math.round(bytes / 1024)} КБ`;
  }

  return megabytesOf(bytes);
}
