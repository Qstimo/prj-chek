/**
 * Сегодняшний день `ГГГГ-ММ-ДД` по местному времени.
 *
 * `sv-SE` даёт ISO-порядок без ручной сборки из частей. Общая утилита:
 * дату подставляют и форма версии, и строка выпуска, и две копии
 * неизбежно разошлись бы в поясе.
 */
export function today(): string {
  return new Intl.DateTimeFormat('sv-SE').format(new Date());
}
