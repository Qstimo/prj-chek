--> Роль приложения получает права на подключение трекера и привязки досок
--> отдельной миграцией: drizzle-kit их не выдаёт, а без них отказ в правах
--> пришёл бы ошибкой драйвера на первом же открытии `/settings`.
--> `UPDATE` нужен обоим: и подключение, и привязка пишутся одним
--> `ON CONFLICT … DO UPDATE` по своему ключу — перечню и проекту.
--> `DELETE` нужен тоже: снятие подключения уносит выгрузки и привязки
--> одним запросом, не трогая задачи (дизайн, 3.3), а привязку человек
--> вправе снять, не заводя взамен другую.
--> Права на секвенции не нужны: суррогатных ключей в обеих таблицах нет
--> вовсе — ключ подключения это значение перечня, ключ привязки это
--> проект, — а перечень `tracker_kind` заведён структурной миграцией.
GRANT SELECT, INSERT, UPDATE, DELETE ON
  tracker_connections,
  tracker_project_bindings
TO cairn_app;
