--> Роль приложения получает права на выгрузки задач отдельной миграцией:
--> drizzle-kit их не выдаёт, а без них отказ в правах пришёл бы ошибкой
--> драйвера на первой же выгрузке — после того, как запись «передали
--> наружу» уже легла в журнал.
--> `UPDATE` нужен двум путям сразу: повторная выгрузка правит задачу в
--> трекере (`PUT /tm/tasks/{id}`), а прогон опроса пишет `checked_at` при
--> **каждом** тике, даже когда ничего не изменилось. Оба идут одним
--> `ON CONFLICT (task_id, tracker) DO UPDATE`.
--> `DELETE` нужен тоже: снятие подключения уносит выгрузки одним запросом,
--> не трогая задачи (дизайн, 3.3), а удаление задачи обязано унести её
--> зеркало явно — ссылка стоит `restrict`, и каскада, который сделал бы это
--> молча, нет.
--> Права на секвенции не нужны: суррогатного ключа у строки нет вовсе —
--> ключ это пара «задача × трекер», — а перечень `tracker_kind` заведён
--> структурной миграцией `0055`.
GRANT SELECT, INSERT, UPDATE, DELETE ON task_exports TO cairn_app;
