import type {
  TrackerKind,
  TrackerProbeResult,
  TrackerTargets,
  TrackerImportCandidate,
  TrackerTaskDetails,
  TrackerImportPreview,
} from '@cairn/shared';

/**
 * Куда класть задачу: привязка проекта, разобранная на три значения.
 *
 * Все три обязательны и приходят вместе: половина привязки — то же
 * «куда-нибудь», от которого привязка и спасает (дизайн, 3.5). Порт их не
 * выбирает и не придумывает — он получает их от того, кто прочитал
 * `tracker_project_bindings`.
 */
export interface TrackerTarget {
  externalProjectId: string;
  boardId: string;
  boardColumnId: string;
}

/**
 * Что уходит наружу при выгрузке: формулировка — и больше ничего.
 *
 * Своим типом, а не `string`, ровно затем, чтобы вопрос «а не добавить ли
 * сюда исполнителя» упирался в этот комментарий: ТЗ 1.4 выносит за объём
 * исполнителей, оценки, даты и комментарии, и ровно за этим задачу и
 * отправляют в трекер — исполнителей ведёт он (дизайн, 2).
 *
 * Описания здесь нет, и это не забывчивость: принимает ли `POST /tm/tasks`
 * поле `description` — живым токеном не проверено (дизайн, 10.4), а слать
 * поле, о котором неизвестно, примут ли его, значит рисковать всей
 * выгрузкой ради необязательного.
 */
export interface TrackerTaskInput {
  title: string;
}

/**
 * Что трекер рассказал о задаче: зеркало его состояния.
 *
 * Ничего не закрывает и ничем не распоряжается: чекпоинт закрывает человек
 * в CAIRN, прогресс версии считается только из чекпоинтов (дизайн, 5).
 * Расхождение «в трекере закрыто, чекпоинт открыт» показывается биркой.
 */
export interface TrackerTaskState {
  /** Идентификатор в трекере: им идёт правка и опрос. */
  externalId: string;
  details?: TrackerTaskDetails | null;
  /**
   * Ссылка для человека либо `null`.
   *
   * `null` — честное «собрать нечего»: формат ссылки без живого токена не
   * проверен, и выдуманная ссылка хуже отсутствующей (дизайн, 10.4).
   */
  externalUrl: string | null;
  /** Где задача лежит **сейчас**, а не куда её кладли. */
  boardId: string | null;
  boardColumnId: string | null;
  isCompleted: boolean;
}

/**
 * Внешний трекер задач.
 *
 * Порт покрывает создание, обновление, опрос, связывание и импорт задач.
 * Четыре исходные операции —
 * про жизнь задачи: `createTask`, `updateTask`, `readTasks`, `probe`.
 * Пятая, `targets`, читает списки проектов, досок и колонок, и появилась
 * она не для выгрузки, а потому что дизайн 9.3 требует: эти списки идут
 * **через нашу ручку**, а не прямым запросом из браузера, — токен не
 * покидает сервер. `readTaskLink` связывает существующую задачу по ссылке.
 * Выполнить это требование, не имея операции в порту,
 * значило бы позвать `fetch` из службы, то есть завести второе место, где
 * предъявляется токен и запрещается переадресация.
 *
 * Чего в порту **нет**: удаления задачи. Удалять чужую задачу по своей
 * кнопке мы не вправе, и удаление в CAIRN не удаляет её в трекере (дизайн,
 * 10.5) — операция, которой нет в порту, не может быть вызвана по
 * недосмотру.
 */
export interface TrackerImportSource {
  tasks: Omit<TrackerImportCandidate, 'existingTaskId' | 'blockedReason'>[];
  people: TrackerImportPreview['people'];
  peopleAvailable: boolean;
  truncated: boolean;
}

export interface Tracker {
  readonly kind: TrackerKind;
  /** Имя узла, куда уйдёт формулировка. `null` — называть нечего. */
  readonly host: string | null;
  readonly isEnabled: boolean;

  /** Кладёт задачу на доску привязки. */
  createTask(
    input: TrackerTaskInput,
    target: TrackerTarget,
    signal: AbortSignal,
  ): Promise<TrackerTaskState>;
  /** Правит уже выгруженную задачу: повторная выгрузка правит, а не двоит. */
  updateTask(
    externalId: string,
    input: TrackerTaskInput,
    signal: AbortSignal,
  ): Promise<TrackerTaskState>;
  /** Спрашивает состояние задач доски. Вебхуков у Weeek нет (дизайн, 10.2). */
  readTasks(target: TrackerTarget, signal: AbortSignal): Promise<TrackerTaskState[]>;
  /** Читает существующую задачу по ссылке и проверяет пространство и доску. */
  readTaskLink(url: string, target: TrackerTarget, signal: AbortSignal): Promise<TrackerTaskState>;
  /** Задачи выбранной доски для импорта, с датами, участниками и признаком неполной выдачи. */
  readImportTasks(target: TrackerTarget, signal: AbortSignal): Promise<TrackerImportSource>;
  /** Списки для привязки: имена, а не идентификаторы, человеку на выбор. */
  targets(signal: AbortSignal): Promise<TrackerTargets>;
  /**
   * Живая проверка связи: читает пространство, ничего не создаёт.
   *
   * Отказ узла — **результат** проверки, а не исключение: наша сторона
   * справилась, когда выяснила, что чужой узел не отвечает. Исключением
   * остаётся выключенный порт, которому спрашивать нечего и не у кого.
   *
   * Ничего не стоит и ничего не создаёт — в отличие от проверки
   * предложителя задач, где наружу уходит фраза и модель на неё отвечает
   * за деньги. Здесь платить нечем по устройству (дизайн, 6).
   */
  probe(signal: AbortSignal): Promise<TrackerProbeResult>;
}

/**
 * Источник адаптера: он рождается **на вызов**, а не на процесс.
 *
 * То же правило, что у предложителя задач и расшифровки: настройка
 * правится на экране и действует без перезапуска API, а адаптер,
 * построенный при старте, молча работал бы по снятому токену. В прогоне
 * опроса порт берётся один раз на тик: увидь решение о задаче и отправка
 * разные настройки, задача уехала бы в трекер, которого в настройке уже нет.
 */
export interface TrackerSource {
  /** Адаптер по действующей настройке. Ненастроенное подключение — выключенный. */
  current(): Promise<Tracker>;
}

/**
 * Токен внедрения источника порта трекера.
 *
 * Символ, а не класс: подменить источник заглушкой обязано быть возможно в
 * тесте и невозможно случайно в сборке.
 */
export const TRACKER_SOURCE = Symbol('TRACKER_SOURCE');

/**
 * Отказ порта трекера с различимым кодом.
 *
 * Код нужен вызывающему, чтобы ответить разным кодом HTTP и разным текстом:
 * «не настроен» — `409` и «попросите администратора», «не ответил» — `502`
 * и «попробуйте ещё раз», «отказал» — `502` и «проверьте настройку».
 *
 * Причину (`cause`) не несёт намеренно, по образцу `SuggesterFailure` и
 * `TranscriberFailure`: в теле чужого ответа и в тексте его ошибки бывает и
 * присланное нами, и сам токен — в сообщении о неверном заголовке, — а
 * любая из них утекла бы отсюда в логи и в обработчик ошибок.
 */
export class TrackerFailure extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'TrackerFailure';
  }
}
