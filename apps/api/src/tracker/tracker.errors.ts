import {
  TRACKER_BAD_URL,
  TRACKER_BINDING_MISSING,
  TRACKER_NOT_CONFIGURED,
} from '@cairn/shared';
import { BadRequestException, ConflictException } from '@nestjs/common';

/**
 * Трекер не настроен: выгружать некуда и спрашивать некого.
 *
 * `409`, а не `404`: подключение — настройка установки, его отсутствие не
 * секрет и не повод скрывать существование проекта. И не `503`: ничего не
 * сломалось — состояние системы мешает операции, и чинится оно действием
 * человека, а не ожиданием.
 */
export class TrackerNotConfiguredError extends ConflictException {
  constructor() {
    super({
      code: TRACKER_NOT_CONFIGURED,
      message: 'Трекер задач не настроен: обратитесь к администратору.',
    });
  }
}

/**
 * У проекта нет привязки доски: класть задачу некуда.
 *
 * `409`, а не `400`: тело запроса в порядке — доска и колонка в него не
 * приходят вовсе и приходить не должны (иначе задачу положили бы на чужую
 * доску, минуя настройку). Мешает состояние проекта, и чинится оно одним
 * действием того же человека.
 *
 * Отдельно от {@link TrackerNotConfiguredError}, потому что чинится другим
 * человеком и на другом экране: подключение — суперадмином на `/settings`,
 * привязку ставит тот, у кого есть запись на «Роадмап» своего проекта.
 * Сведение их в «трекер не готов» послало бы подрядчика к администратору за
 * тем, что он может сделать сам (дизайн, 3.5).
 *
 * Называется **первой**, прежде ненастроенного подключения: привязка — это
 * настройка его собственного проекта, и отдать ему сначала отказ про чужую
 * настройку значило бы отправить его к администратору, не сказав, что у него
 * и доска не выбрана, — то есть два похода вместо одного.
 */
export class TrackerBindingMissingError extends ConflictException {
  constructor() {
    super({
      code: TRACKER_BINDING_MISSING,
      message: 'Доска трекера для проекта не выбрана: укажите, куда выгружать задачи.',
    });
  }
}

/**
 * Адрес подключения негоден.
 *
 * `400`, потому что негодно присланное тело. Схема контракта проверяет то
 * же самое и отвечает раньше; это вторая стена — для путей записи, которые
 * схему не проходят (например, вызов службы из другой службы).
 */
export class TrackerBadUrlError extends BadRequestException {
  constructor() {
    super({
      code: TRACKER_BAD_URL,
      message: 'Адрес трекера негоден: нужен https без строки запроса.',
    });
  }
}
