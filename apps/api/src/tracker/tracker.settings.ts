import type { TrackerKind } from '@cairn/shared';

/**
 * Сколько ждём ответа трекера, в секундах.
 *
 * **Константа, а не колонка подключения и не переменная окружения**, и обе
 * альтернативы отвергнуты по разному. Колонки у `tracker_connections` нет
 * вовсе (дизайн, 3.4), и завести её значило бы предложить администратору
 * настраивать то, что не свойство провайдера, а свойство **нашего** обмена:
 * у Weeek нет длинных операций — ни распознавания, ни генерации, — а четыре
 * вызова порта это четыре коротких REST-запроса. Переменная окружения
 * завела бы настройку, о которой не говорит ни README, ни экран, то есть
 * ровно ту полосу имён переменных, которую с карточки узла модели уже
 * снимали.
 *
 * Значение же нужно именно в настройках адаптера, а не литералом внутри
 * `fetch`: иначе тест, проверяющий поведение по сроку, менял бы время, а не
 * настройку.
 */
export const TRACKER_TIMEOUT_SECONDS = 20;

/**
 * Что адаптеру нужно знать, чтобы дойти до трекера.
 *
 * Токен здесь открытый, и это единственный тип в системе трекера, в
 * котором он открытый: расшифровка живёт внутри процесса, а проекция для
 * экрана — своим типом контракта без токена. Один тип на оба случая означал
 * бы, что токен попадает в ответ при первой же забытой проекции.
 */
export interface TrackerSettings {
  kind: TrackerKind;
  baseUrl: string;
  /** Открытый токен. Пустая строка означает «порт выключен». */
  token: string;
  /** Имя узла из адреса: идёт в журнал и в сообщение отказа, адрес — никуда. */
  host: string | null;
  /**
   * Рабочее пространство. Нужно **только** человеческой ссылке на задачу:
   * ни одной из операций порта оно не требуется — токен сам принадлежит
   * пространству (дизайн, 10.4).
   */
  workspaceId: string | null;
  timeoutSeconds: number;
  isEnabled: boolean;
}
