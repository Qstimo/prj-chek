/** Имя переменной интервала тика. `0` выключает цикл целиком. */
export const TRACKER_POLL_ENV = 'CAIRN_TRACKER_POLL_SECONDS';

/** Как часто спрашиваем трекер о состоянии задач, в секундах. */
export const DEFAULT_TRACKER_POLL_SECONDS = 300;

/**
 * Интервал тика прогона опроса (дизайн, 8).
 *
 * Пять минут, а не минута: вебхуков у Weeek в публичном API нет вовсе
 * (дизайн, 10.2), статус заведомо запаздывает, и спорить тут можно лишь о
 * том, насколько. Минутный шаг дал бы в двенадцать раз больше запросов в
 * чужой API, который считает частоту, ради знания, которым никто не
 * распоряжается автоматически: зеркало ничего не закрывает (дизайн, 5), и
 * видит его человек, пришедший на экран задач.
 *
 * `0` выключает цикл целиком — так работают тесты и локальная разработка, и
 * выключателю здесь, как у частого опроса лежащих адресов, место есть: без
 * него установка без подключения трекера всё равно поднимала бы таймер и
 * раз в пять минут читала настройку из базы.
 *
 * Мусор, пустая строка и отрицательное значение означают **умолчание**, а не
 * «никогда»: выключение — решение человека, и выражено оно нулём. Пустая
 * строка отдельно названа потому, что compose передаёт необъявленную
 * переменную (`${VAR:-}`) именно ею, а не отсутствующей: прочитать её как
 * нуль значило бы молча остановить наблюдение у всех, кто переменной не
 * задавал.
 */
export function trackerPollSecondsOf(value: string | undefined): number {
  if (value !== undefined && value.trim() === '0') {
    return 0;
  }

  const seconds = Number(value);

  // `Number('')` — нуль, и пустая строка иначе выключила бы цикл: отсюда
  // проверка на положительность, а не на конечность.
  return Number.isFinite(seconds) && seconds > 0
    ? Math.round(seconds)
    : DEFAULT_TRACKER_POLL_SECONDS;
}
