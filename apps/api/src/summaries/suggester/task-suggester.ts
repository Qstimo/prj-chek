import type { ModelProbeResult, ModelServicePlacement } from '@cairn/shared';

/** Одна предложенная задача. Только формулировка — больше у чекпоинта нет. */
export interface TaskSuggestion {
  title: string;
}

/** Итог вызова: формулировки и сколько элементов ответа отброшено. */
export interface SuggestResult {
  tasks: TaskSuggestion[];
  dropped: number;
}

/**
 * Предложитель задач: превращает текст саммари в список формулировок.
 *
 * Возвращает **предложение**, а не результат: применяет его человек
 * отдельным действием (ТЗ 5.3). Поэтому у порта нет ни доступа к данным
 * проекта, ни права писать — он получает строку и отдаёт строки. Это и
 * есть причина, по которой инструмент безопасен при внедрении инструкций
 * в текст созвона: эскалации из вывода нет физически (дизайн, 5.6).
 */
export interface TaskSuggester {
  /** Где стоит узел: `external` либо `local`. Для журнала и экрана. */
  readonly placement: ModelServicePlacement;
  /** Модель, заданная настройкой. */
  readonly model: string;
  /**
   * Имя узла, куда уйдёт текст. Показывается пользователю.
   *
   * `null` — когда называть нечего: порт выключен или настроенный адрес
   * имени узла не даёт. Называть узел, куда ничего не уходит, значило бы
   * врать подписью над кнопкой.
   */
  readonly host: string | null;
  /** Предел объёма текста: длиннее — отказ, а не молчаливое обрезание. */
  readonly maxChars: number;
  /** Настроен ли: без адреса или ключа порт выключен. */
  readonly isEnabled: boolean;
  suggest(text: string, signal: AbortSignal): Promise<SuggestResult>;
  /**
   * Живая проверка связи. Наружу уходит константа, не данные проекта.
   *
   * В порту, а не в службе администрирования: без неё неверный ключ
   * выясняется на первом созвоне, через дни после правки настройки
   * (дизайн, 8.1). Отказ узла — **результат** проверки, а не исключение:
   * исключением остаётся только выключенный порт, которому проверять
   * нечего.
   */
  probe(signal: AbortSignal): Promise<ModelProbeResult>;
}

/**
 * Источник адаптера: он рождается **на вызов**, а не на процесс.
 *
 * Прежде фабрика модуля строила адаптер один раз при старте, и правка
 * настройки не действовала на ходу — ни с экрана, ни через `.env`,
 * несмотря на то, что разбор окружения честно перечитывался при каждом
 * обращении. Запрет «порт выбирается один раз при старте» отменён
 * названно, и цена названа: граница передачи данных перестаёт быть
 * неизменной за время жизни процесса. Взамен каждая смена попадает в
 * журнал, а подпись над кнопкой не может отстать от настройки
 * (дизайн, 9.1).
 *
 * Запрет, который при этом **остаётся**: система сама узел не меняет —
 * автоматического перехода на внешний узел при отказе локального нет и не
 * будет.
 */
export interface TaskSuggesterSource {
  /** Адаптер по действующей настройке. Ненастроенный узел — выключенный. */
  current(): Promise<TaskSuggester>;
}

/**
 * Токен внедрения источника.
 *
 * Прежний `TASK_SUGGESTER` удалён, а не оставлен рядом: тест, подменивший
 * его заглушкой-адаптером, обязан упасть типом, а не начать вести себя
 * странно (дизайн, 9.2).
 */
export const TASK_SUGGESTER_SOURCE = Symbol('TASK_SUGGESTER_SOURCE');

/**
 * Отказ порта с различимым кодом.
 *
 * Код нужен вызывающему, чтобы ответить разным кодом HTTP: «не настроен»
 * — это `409` и «попросите администратора включить», а «не ответил» —
 * `502` и «попробуйте ещё раз».
 *
 * Причину (`cause`) не несёт намеренно: в теле чужого ответа и в тексте
 * его ошибки бывает и присланный нами текст созвона, и подробности о
 * ключе, а любая из них утекла бы отсюда в логи и в обработчик ошибок.
 * Сообщение собирается из кода и имени узла — больше ниоткуда.
 */
export class SuggesterFailure extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'SuggesterFailure';
  }
}
