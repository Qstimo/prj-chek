/** Что `ffprobe` узнал о файле. */
export interface MediaProbe {
  /** Есть ли звуковая дорожка. */
  hasAudio: boolean;
  /** Имя кодека дорожки, как его назвал `ffprobe`; `null` — дорожки нет. */
  audioCodec: string | null;
  /** Длительность в секундах, если контейнер её знает. */
  durationSeconds: number | null;
}

/** Извлечённая дорожка: путь внутри каталога записей и её размер. */
export interface ExtractedAudio {
  path: string;
  bytes: number;
  type: string;
}

/**
 * Извлечение звуковой дорожки из загруженной записи.
 *
 * **Порт отдельный от `Transcriber`, а не его метод**, и это решение:
 * извлечение не уходит наружу, не стоит денег, не имеет узла и
 * настраивается своими переменными. Слепить их значило бы дать выключенной
 * расшифровке выключить и извлечение — а установка с `ffmpeg` и без ключа
 * вполне осмысленна: она принимает видео, извлекает дорожку и честно
 * говорит, что отправлять её некуда (дизайн, 7.6).
 *
 * Прямое следствие той же разницы — решения о повторах: прерванное
 * извлечение повторяется молча, потому что идёт на нашей машине и ничего
 * не раскрывает, а прерванная отправка наружу — нет (`job-decision.ts`).
 *
 * Ключа службы этот порт не видит ни одним полем: ему нечего предъявлять.
 */
export interface AudioExtractor {
  /** Доступно ли извлечение: есть исполняемый файл и он не выключен. */
  readonly isAvailable: boolean;
  /**
   * Битрейт дорожки: показывается человеку в подписи о передаче.
   *
   * Обнуляем, в отличие от снимка дизайна: у недоступного извлечения
   * битрейта нет, и `audioBitrate` в контракте тоже обнуляем
   * (`transcriberInfoSchema`). Назвать число там, где перекодировать
   * нечем, значило бы соврать подписью.
   */
  readonly bitrate: string | null;
  /** Что умеет принимать загрузка при этом состоянии извлечения. */
  readonly acceptedTypes: string[];

  /** Смотрит, что внутри. Секунды работы: читает заголовки, не весь файл. */
  probe(uploadPath: string, signal: AbortSignal): Promise<MediaProbe>;
  /** Извлекает дорожку. Минуты работы; `signal` убивает процесс. */
  extract(uploadPath: string, jobId: string, signal: AbortSignal): Promise<ExtractedAudio>;
}

/**
 * Токен внедрения порта извлечения.
 *
 * Свой, а не общий с `TASK_SUGGESTER_SOURCE` и расшифровкой: оба порта
 * обязаны выключаться независимо, и общий токен сделал бы это невозможным
 * физически.
 */
export const AUDIO_EXTRACTOR = Symbol('AUDIO_EXTRACTOR');

/** Что видно после запуска дочернего процесса. */
export interface ProcessOutcome {
  /** `stdout` целиком: у `ffprobe` это JSON, у `ffmpeg` — пусто. */
  stdout: string;
  /**
   * Хвост `stderr`.
   *
   * Хвост, а не всё: `ffmpeg` на негодном входе пишет тысячи строк, и
   * держать их в куче процесса, который делит машину с базой, незачем.
   */
  stderrTail: string;
  /** Код выхода; `null` — процесс до выхода не дошёл. */
  exitCode: number | null;
  /** Убит сигналом — у нас это всегда наш предел времени. */
  killed: boolean;
}

/**
 * Запуск дочернего процесса — **внедряемой** функцией.
 *
 * Внедряемой, а не вызовом `child_process` внутри адаптера, ровно по
 * запрету плана: ни один тест не запускает `ffmpeg`. Тест подменяет эту
 * функцию и проверяет, с чем именно адаптер пошёл бы к процессу, — а это
 * и есть то, что здесь важно (массив аргументов, `--`, `-nostdin`).
 *
 * Аргументы **массивом**: `spawn` с массивом не запускает оболочку вовсе,
 * значит имя файла не может быть истолковано как команда. Имена у нас свои
 * (идентификаторы задач), но правило должно стоять до того, как
 * кто-нибудь решит передать сюда присланное имя (дизайн, 7.6).
 */
export type ProcessRunner = (
  command: string,
  args: string[],
  signal: AbortSignal,
) => Promise<ProcessOutcome>;

/**
 * Отказ извлечения с различимым кодом.
 *
 * Код нужен вызывающему, чтобы сказать человеку, что делать: «нет
 * дорожки» — выгрузить созвон со звуком, «битый контейнер» — выгрузить
 * заново, «не вышло» — нажать «снова» (дизайн, 7.5).
 *
 * Причину (`cause`) не несёт намеренно, по образцу `SuggesterFailure`: в
 * `stderr` у `ffmpeg` бывают пути, имена кодеков и обрывки содержимого, и
 * любой из них утёк бы отсюда в логи и в обработчик ошибок.
 */
export class ExtractionFailure extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'ExtractionFailure';
  }
}
