import type { TranscriptionJobRow } from '../../db/schema';

/**
 * Уникальные непустые пути файлов задач расшифровки.
 *
 * Своим файлом, а не методом репозитория, по одной причине: её зовут три
 * места — репозиторий расшифровок, репозиторий саммари и репозиторий
 * хроники, — и последнему пришлось бы импортировать класс репозитория,
 * который от него уже зависит.
 *
 * Схлопывание в множество обязательно, и причин две сразу: когда
 * извлечение не понадобилось, обе колонки держат **одну и ту же строку**
 * (загруженный `mp3` и есть дорожка), а у задачи, дошедшей до `done`,
 * `upload_path` уже пуст — исходник убран при укладке текста. Поэтому «до
 * двух путей на задачу» на деле почти всегда один (дизайн, 2.5 пункт 1).
 */
export function mediaPathsOf(
  rows: Pick<TranscriptionJobRow, 'uploadPath' | 'audioPath'>[],
): string[] {
  const paths = new Set<string>();

  for (const row of rows) {
    if (row.uploadPath) paths.add(row.uploadPath);
    if (row.audioPath) paths.add(row.audioPath);
  }

  return [...paths];
}
