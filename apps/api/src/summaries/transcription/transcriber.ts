import type { ModelProbeResult, TranscriberKind, TranscriptionState } from '@cairn/shared';

/** Что отдать на расшифровку: файл в нашем хранилище, не произвольный адрес. */
export interface TranscriptionInput {
  /**
   * Имя файла **дорожки** внутри каталога записей. Не URL и не путь
   * снаружи. Загруженный файл порту расшифровки не показывается вовсе: он
   * работает только с тем, что уже пригодно службе.
   */
  audioPath: string;
  audioType: string;
}

/** Ответ службы на один обмен: её состояние и, если готово, текст. */
export interface TranscriptionAnswer {
  state: TranscriptionState;
  /** Текст — только при `done`. */
  text: string | null;
  /** Код отказа — только при `failed`. */
  code: string | null;
  /** Чем опрашивать дальше; `null` — опрашивать нечего. */
  externalId: string | null;
}

/**
 * Расшифровка записи созвона внешней или своей службой.
 *
 * **Пять отличий от интерфейса раздела 6.1 первой итерации**, и причина
 * каждого — иначе следующий читатель сверит с прежним дизайном и решит,
 * что порт разошёлся случайно:
 *
 * 1. **`start` возвращает ответ, а не идентификатор.** Прежняя подпись
 *    `start(): Promise<string>` предполагала, что работа всегда длинная и
 *    всегда асинхронная. Для SpeechKit это верно, для локального
 *    `faster-whisper` — нет: он отвечает одним синхронным запросом с
 *    готовым текстом, и с прежней подписью ему пришлось бы придумывать
 *    идентификатор и держать результат в памяти процесса — ровно то
 *    состояние в памяти, от которого фоновая задача и избавляет.
 * 2. **`poll` принимает идентификатор провайдера, а не наш.** Прежний
 *    `poll(jobId)` отдавал нашу строку целиком; строка наша и лежит в
 *    нашей таблице, а порт отвечает за один обмен со службой.
 * 3. **`cancel` заменён на `forget`.** `cancel` обещал то, чего может не
 *    быть: поддерживает ли SpeechKit отмену запущенной операции — не
 *    проверено (пункт 5 таблицы проверок). А попросить провайдера убрать
 *    **результаты**, которые иначе лежат у него 3 суток, нужно наверняка.
 *    Отмена человеком закрывает нашу задачу локально и зовёт `forget`;
 *    обещать остановку чужой работы дизайн не будет.
 * 4. **Добавлены `maxSendBytes`, `serviceTypes`, `isEnabled`** — по
 *    образцу `TaskSuggester`. Пределы принадлежат адаптеру, потому что
 *    это его пределы: внешний знает 60 МБ и три контейнера, локальный с
 *    `ffmpeg` внутри принял бы и больше, и шире.
 * 5. **Порт видит дорожку, а загруженного файла не видит вовсе** — правка
 *    этого дизайна вслед за появлением извлечения.
 *
 * Чего здесь **нет**: предела загрузки и широкого списка форматов. Они
 * принадлежат извлечению (`extractor.ts`), а не службе: держать их здесь
 * значило бы заставить выключенную расшифровку выключить и приём
 * видеозаписей, то есть связать развязанное по природе.
 */
export interface Transcriber {
  readonly kind: TranscriberKind;
  readonly model: string;
  /** Имя узла, куда уйдёт дорожка. `null` — называть нечего. */
  readonly host: string | null;
  /** Предел отправки: больше этого служба не возьмёт (дизайн, 3.6). */
  readonly maxSendBytes: number;
  /** Какие контейнеры служба принимает **как есть**, без извлечения. */
  readonly serviceTypes: string[];
  readonly isEnabled: boolean;

  /** Отдаёт дорожку службе. Ответ может быть и `running`, и сразу `done`. */
  start(input: TranscriptionInput, signal: AbortSignal): Promise<TranscriptionAnswer>;
  /** Спрашивает о судьбе работы. Бесплатно и ничего не раскрывает. */
  poll(externalId: string, signal: AbortSignal): Promise<TranscriptionAnswer>;
  /** Просит службу забыть результаты. Best effort: отказ не меняет исхода. */
  forget(externalId: string): Promise<void>;
  /**
   * Живая проверка связи. Наружу не уходит ни байта записи.
   *
   * В порту, а не в службе администрирования, — по образцу
   * {@link TaskSuggester.probe}: без неё негодный ключ выясняется на первом
   * созвоне, через дни после правки настройки. Отказ узла — **результат**
   * проверки, а не исключение; исключением остаётся выключенный порт,
   * которому спрашивать нечего и не у кого.
   *
   * Отличие от проверки предложителя названо: у разбивки наружу уходит
   * фраза-константа, то есть настоящий вызов модели, а у распознавания
   * настоящий вызов означал бы отправку аудио и оплату. Поэтому проверка
   * спрашивает о работе, которой нет, и платить за неё нечем.
   */
  probe(signal: AbortSignal): Promise<ModelProbeResult>;
}

/**
 * Источник адаптера: он рождается **на вызов**, а не на процесс.
 *
 * Прежняя фабрика модуля строила адаптер один раз при старте, и правка
 * настройки не действовала на ходу — ни с экрана, ни через `.env`. Запрет
 * «узел расшифровки настраивается только окружением, адаптер строится при
 * старте» отменён названно, и цена та же, что назвал предложитель задач:
 * граница передачи данных перестаёт быть неизменной за время жизни
 * процесса. Взамен каждая смена попадает в журнал, а подпись «запись
 * уйдёт туда-то» не может отстать от настройки.
 *
 * Запрет, который **остаётся**: система сама узел не меняет —
 * автоматического перехода на внешний узел при отказе локального нет.
 */
export interface TranscriberSource {
  /** Адаптер по действующей настройке. Ненастроенный узел — выключенный. */
  current(): Promise<Transcriber>;
}

/**
 * Токен внедрения источника порта расшифровки.
 *
 * Свой, отдельный от {@link AUDIO_EXTRACTOR}: оба порта обязаны
 * выключаться независимо, и установка с `ffmpeg` и без ключа осмысленна —
 * она принимает видео, извлекает дорожку и честно говорит, что отправлять
 * её некуда.
 *
 * Прежний `TRANSCRIBER` удалён, а не оставлен рядом — по образцу
 * `TASK_SUGGESTER`: тест, подменивший его заглушкой-адаптером, обязан
 * упасть типом, а не начать вести себя странно.
 */
export const TRANSCRIBER_SOURCE = Symbol('TRANSCRIBER_SOURCE');

/**
 * Отказ порта расшифровки с различимым кодом.
 *
 * Код нужен вызывающему, чтобы ответить разным кодом HTTP и разным текстом:
 * «не настроен» — это `409` и «попросите администратора включить», «не
 * ответил» — `502` и «попробуйте ещё раз».
 *
 * Причину (`cause`) не несёт намеренно, по образцу `SuggesterFailure`: в
 * теле чужого ответа и в тексте его ошибки бывает и присланное нами, и
 * подробности о ключе — вплоть до самого ключа в строке запроса, — а любая
 * из них утекла бы отсюда в логи и в обработчик ошибок.
 */
export class TranscriberFailure extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'TranscriberFailure';
  }
}
