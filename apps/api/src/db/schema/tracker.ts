import { TrackerKind, type TrackerTaskDetails } from '@cairn/shared';
import {
  boolean,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';

import { projects } from './projects';
import { subjects } from './subjects';
import { projectTasks } from './tasks';

/** Вид внешнего трекера. Значения совпадают с контрактом. */
export const trackerKindEnum = pgEnum('tracker_kind', [TrackerKind.Weeek]);

/**
 * Подключение к внешнему трекеру задач (дизайн, 3.4).
 *
 * **`kind` первичным ключом** — то же расхождение с соглашением
 * репозитория, что у `model_services`, и по тем же трём причинам: строка
 * здесь не сущность, а настройка — её не создают и не удаляют по одной, по
 * ней не ходят ссылки, и таких строк ровно столько, сколько значений в
 * перечне. Перечень ключом даёт «одно подключение на вид трекера»
 * инвариантом базы, превращает запись в один `ON CONFLICT (kind) DO UPDATE`
 * без гонки между двумя вкладками администратора и делает адрес ручки
 * читаемым по смыслу, а не по `uuid`, который суперадмину пришлось бы
 * сначала узнать списком.
 *
 * **Запасного источника в окружении нет, и это решение, а не недоделка**
 * (дизайн, 3.4). У узлов модели окружение осталось потому, что по прежнему
 * README собраны работающие установки; подключения трекера не было никогда,
 * собранных по нему установок не существует, и второй источник пришлось бы
 * поддерживать ради пустого множества. Отсюда и отсутствие поля «источник»
 * в проекции контракта: ответ на вопрос «откуда настройка» здесь всегда
 * один.
 *
 * **Колонки размещения нет**, в отличие от узла модели: там `placement`
 * решает, допустим ли `http` — у своей службы в контуре он обычное дело.
 * Трекер чужой и облачный, `https` безусловен, и колонка с одним законным
 * значением намекала бы, что второе тоже законно.
 */
export const trackerConnections = pgTable('tracker_connections', {
  kind: trackerKindEnum('kind').primaryKey(),
  /**
   * Адрес одной строкой, а не «узел» плюс «путь»: человек копирует его из
   * документации провайдера (`https://api.weeek.net/public/v1`). Имя узла
   * выводится из адреса, а не хранится — вторая копия разошлась бы при
   * правке.
   */
  baseUrl: text('base_url').notNull(),
  /**
   * Токен под `CryptoService`, формат `v1:nonce:ct:tag` — тот же шифр, что
   * у значений переменных проекта.
   *
   * Обнуляем, и `null` означает ровно «токена нет», то есть «порт выключен,
   * кнопки выгрузки нет вовсе». Не пустая строка: пустая строка в
   * шифрованной колонке — это шифротекст пустого значения, то есть «токен
   * задан и он пустой», и различать их пришлось бы расшифровкой. Имя
   * колонки — как у `model_services.secret_encrypted` и
   * `variable_versions.value_encrypted`: «шифровано» видно в самой схеме, а
   * не только в коде, который с ней работает.
   */
  secretEncrypted: text('secret_encrypted'),
  /**
   * Рабочее пространство Weeek. Обнуляемо и работу **не блокирует**: токен
   * сам принадлежит пространству, и ни одной из четырёх операций порта этот
   * идентификатор не нужен. Нужен он человеческой ссылке на задачу, формат
   * которой без живого токена не проверен (дизайн, 10.4), — поэтому пустое
   * значение означает «ссылку возьмём из ответа», а не «настройка неполна».
   */
  workspaceId: text('workspace_id'),
  /**
   * Решение человека «включено», отдельно от полноты настройки.
   *
   * Нужен, чтобы выключить выгрузку, не стирая токен: пространство
   * переехало, платить за лишние запросы не хотим, токен терять не хотим.
   */
  isEnabled: boolean('is_enabled').notNull().default(true),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  /** «Кто и когда» прямо на экране, а не поиском по журналу. */
  updatedBySubjectId: uuid('updated_by_subject_id')
    .notNull()
    .references(() => subjects.id, { onDelete: 'restrict' }),
});

/**
 * Куда выгружать задачи проекта: его доска в трекере (дизайн, 3.5).
 *
 * Ровно то, о чём сказал владелец: **разные проекты — разные доски**. Без
 * привязки выгрузка отказывает названной причиной
 * (`TRACKER_BINDING_MISSING`), а не кладёт задачу «куда-нибудь».
 *
 * **`project_id` первичным ключом**: трекер на установку один (дизайн,
 * 10.1), и составной ключ «проект × трекер» выражал бы правило, которого
 * пока нет. Вид трекера всё равно назван колонкой — по ней вторая привязка
 * получит свой ключ, не переписывая существующие строки, и по ней же видно,
 * в какой трекер эта доска ведёт.
 *
 * Все три идентификатора обязательны: привязка без колонки — то же
 * «куда-нибудь», только записанное в базу. Тип — `text`, хотя Weeek отдаёт
 * числа: арифметики над ними нет, у второго трекера они могут быть не
 * числом, а большое число потеряло бы точность в JS молча.
 */
export const trackerProjectBindings = pgTable('tracker_project_bindings', {
  /**
   * `restrict`, как у `project_tasks.project_id`: привязка — настройка
   * проекта, и каскад унёс бы вместе с проектом ответ на вопрос «куда мы
   * его выгружали».
   */
  projectId: uuid('project_id')
    .primaryKey()
    .references(() => projects.id, { onDelete: 'restrict' }),
  tracker: trackerKindEnum('tracker').notNull(),
  externalProjectId: text('external_project_id').notNull(),
  boardId: text('board_id').notNull(),
  boardColumnId: text('board_column_id').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  updatedBySubjectId: uuid('updated_by_subject_id')
    .notNull()
    .references(() => subjects.id, { onDelete: 'restrict' }),
});

/**
 * Выгрузка задачи и зеркало её состояния в трекере (дизайн, 3.3).
 *
 * Своя таблица, а не колонки у задачи, по трём причинам, и каждая стоит
 * отдельно:
 *
 * 1. **Зеркало чужого состояния не лежит в строке, которую правит человек.**
 *    Опрос пишет сюда каждые пять минут, формулировку правят раз в неделю.
 *    Один `UPDATE` на обе цели — это конфликт правок там, где его можно
 *    просто не создавать. Тот же приём, что у инцидента адреса: наблюдение
 *    живёт своими строками.
 * 2. **Второй трекер не потребует переделки**: ключ — пара «задача ×
 *    трекер», и вторая выгрузка той же задачи ляжет рядом.
 * 3. **Снятие подключения уносит выгрузки одним `DELETE`**, не трогая задачи.
 *
 * **Зеркало ничего не закрывает** (решение владельца, дизайн 5). Прогресс
 * версии считается из `roadmap_checkpoints.is_done` и только из них, а
 * «закрыта там, открыта здесь» — законное состояние, которое экран
 * показывает биркой. Автоматическое закрытие означало бы, что упавший
 * опрос, снятый токен или переименованная колонка молча останавливают
 * прогресс роадмапа; вебхуков у Weeek в публичном API нет вовсе (дизайн,
 * 1), и состояние приходит только опросом.
 *
 * **Ключ составной, а суррогатного `id` нет**: ссылок на строку выгрузки
 * нет ни одной, и `id` рядом с уникумом дал бы два способа назвать одну
 * строку. Он же превращает повторную выгрузку и запись опроса в один
 * `ON CONFLICT (task_id, tracker) DO UPDATE` — без гонки между выгрузкой и
 * прогоном.
 */
export const taskExports = pgTable(
  'task_exports',
  {
    /**
     * `restrict`, а не каскад: задача в трекере остаётся жить (дизайн,
     * 10.5) — удалять чужую задачу по своей кнопке мы не вправе, — и
     * строку зеркала обязан унести явный путь удаления, который и решает,
     * что сказать человеку. Каскад унёс бы её молча, и ответ на вопрос «а
     * в Weeek она осталась?» пропал бы вместе со строкой.
     */
    taskId: uuid('task_id')
      .notNull()
      .references(() => projectTasks.id, { onDelete: 'restrict' }),
    tracker: trackerKindEnum('tracker').notNull(),
    /**
     * Идентификатор задачи в трекере: им идут и правка (`PUT /tm/tasks/{id}`),
     * и опрос.
     *
     * Обязателен, и состояния «выгрузка есть, а идентификатора нет» не
     * бывает: строка заводится только после удачного создания задачи в
     * трекере, а отказ её не создаёт вовсе (план, C2).
     */
    externalId: text('external_id').notNull(),
    /**
     * Ссылка для человека, и это **не** `project_tasks.url`.
     *
     * `url` вписал человек, и выгрузка его не перезаписывает (дизайн, 3.1):
     * одно поле на две ссылки означало бы, что первая же выгрузка затёрла
     * заметку, которую человек держал именно там.
     *
     * Обнуляема: формат ссылки Weeek живым токеном не проверен (дизайн,
     * 10.4), и пусто честно означает «мы её не знаем» — в отличие от
     * собранной по выдуманному шаблону, которая увела бы на `404`.
     */
    externalUrl: text('external_url'),
    /** Куда положили: доска из привязки, известна до первого байта. */
    externalBoardId: text('external_board_id').notNull(),
    /**
     * Где лежит сейчас. Обнуляема, потому что приходит **ответом** трекера,
     * а ответ может колонку не назвать; подставить туда колонку привязки
     * значило бы утверждать, что задачу не двигали, — ровно то, за чем на
     * этот экран и смотрят.
     */
    externalColumnId: text('external_column_id'),
    /** Закрыта ли задача **там**. Здесь не закрывает ничего. */
    details: jsonb('details').$type<TrackerTaskDetails>(),
    isCompleted: boolean('is_completed').notNull().default(false),
    exportedAt: timestamp('exported_at', { withTimezone: true }).notNull().defaultNow(),
    /** Когда последний раз правили задачу в трекере или её зеркало. */
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
    /**
     * Когда **спрашивали** состояние.
     *
     * Пишется при каждом опросе, даже когда ничего не изменилось: иначе
     * «давно не спрашивали» не отличить от «не менялось» — та же ошибка,
     * что аптайм без пропусков наблюдения. Обнуляемо, и пусто означает
     * ровно «опроса ещё не было»; подставить сюда `exported_at` значило бы
     * утверждать, что статус спрашивали, хотя не спрашивали ни разу.
     */
    checkedAt: timestamp('checked_at', { withTimezone: true }),
    /**
     * Код последней неудачи обмена (`TRACKER_UNAVAILABLE`,
     * `TRACKER_REJECTED`), `null` после удачи.
     *
     * Код, а не текст чужого ответа: в теле ответа бывает и эхо
     * присланного, и сам токен в сообщении о неверном заголовке, а эта
     * колонка уезжает на экран задачи.
     */
    failureCode: text('failure_code'),
  },
  (table) => [primaryKey({ columns: [table.taskId, table.tracker] })],
);

/** Строка подключения трекера. Токен здесь шифрованный. */
export type TrackerConnectionRow = typeof trackerConnections.$inferSelect;

/** Строка привязки проекта к доске трекера. */
export type TrackerProjectBindingRow = typeof trackerProjectBindings.$inferSelect;

/** Строка выгрузки задачи: зеркало её состояния в трекере. */
export type TaskExportRow = typeof taskExports.$inferSelect;
