import type { IncidentProbe } from '@cairn/shared';
import { sql } from 'drizzle-orm';
import {
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { environmentDomains } from './environments';

/**
 * Падение адреса как отрезок времени (дизайн уведомлений, раздел 3).
 *
 * Строка статуса отвечает на вопрос «как сейчас» и перезаписывается; здесь
 * лежит «когда и сколько». Открытый инцидент — он же ответ на «лежит с
 * какого момента», и колонки `down_since` в статусе нет намеренно: второе
 * место хранения того же факта разошлось бы с первым.
 *
 * Частичный уникальный индекс делает второй пуш об одном падении
 * невозможным: правило живёт в базе, а не в памяти процесса, и перезапуск
 * API не рассылает заново то, что уже известно.
 *
 * Ссылка `restrict`, а не каскад: каскадов в проекте нет, строки уносит
 * репозиторий окружений явно, в той же транзакции, что и строки статусов.
 */
export const addressIncidents = pgTable(
  'address_incidents',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    domainId: uuid('domain_id')
      .notNull()
      .references(() => environmentDomains.id, { onDelete: 'restrict' }),
    startedAt: timestamp('started_at', { withTimezone: true }).notNull().defaultNow(),
    /** Обнуляемый: пусто — адрес не отвечает до сих пор. */
    resolvedAt: timestamp('resolved_at', { withTimezone: true }),
    /** Причина на момент падения; могла и не определиться. */
    cause: text('cause'),
    /**
     * Причина на последней проверке, заставшей адрес упавшим.
     *
     * Вторая колонка, а не правка первой: падение длится часами, и
     * «с чего началось» и «чем кончилось» — разные вопросы. Пока
     * колонка была одна, причина замерзала на открытии.
     */
    lastCause: text('last_cause'),
    /**
     * Время последней проверки, заставшей адрес упавшим.
     *
     * Вместе с `resolved_at` ограничивает момент возвращения сверху и
     * снизу: адрес поднялся где-то между ними. Точнее прогон не
     * измеряет, и делать вид, что измеряет, нельзя.
     */
    lastDownAt: timestamp('last_down_at', { withTimezone: true }),
    /** Сколько проверок подтвердили падение, считая открывшую. */
    checks: integer('checks').notNull().default(1),
    /**
     * Слепок момента падения: куда смотрело имя и что с портами машины.
     *
     * `jsonb`, а не своя таблица и не набор колонок. Таблица потребовала
     * бы ещё одной ссылки и ещё одного места, где строки уносят руками:
     * инциденты удаляет репозиторий окружений явно, в той же транзакции,
     * и забытый ребёнок запретил бы снятие адреса. Колонки же пришлось бы
     * заводить парами на каждый порт. Разбирать слепок по частям в
     * запросах не нужно никогда: он снимается один раз, читается целиком
     * и не меняется — как метаданные журнала действий.
     *
     * Форму держит zod на входе и на выходе; обнуляемый, потому что у
     * строк до его появления слепка нет, и выдумывать его задним числом
     * нельзя — он описывал бы сегодняшнюю сеть, а не ту, что была тогда.
     */
    probe: jsonb('probe').$type<IncidentProbe>(),
  },
  (table) => [
    uniqueIndex('address_incidents_open')
      .on(table.domainId)
      .where(sql`${table.resolvedAt} is null`),
    // Для чтения истории: частичный индекс выше видит только открытые
    // строки, а экран адреса читает все.
    index('address_incidents_domain').on(table.domainId, table.startedAt.desc()),
  ],
);

/** Строка инцидента. */
export type AddressIncidentRow = typeof addressIncidents.$inferSelect;
