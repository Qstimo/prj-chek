import { TranscriberKind, TranscriptionState } from '@cairn/shared';
import { sql } from 'drizzle-orm';
import {
  date,
  index,
  integer,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { projects } from './projects';
import { subjects } from './subjects';
import { summaries } from './summaries';

/**
 * Вид службы расшифровки: куда уходит запись.
 *
 * Свой `pgEnum`, а не `text`, и расхождение с `summaries.suggester_name`
 * намеренное: там колонка называется «name» и заполняется видом адаптера
 * постольку-поскольку, здесь значение — ровно перечень контракта, и
 * перечень в базе делает невозможное значение невозможным. Второй `pgEnum`
 * рядом с `summary_task_origin` — не новый механизм (дизайн, 2.1).
 */
export const transcriberKindEnum = pgEnum('transcriber_kind', [
  TranscriberKind.External,
  TranscriberKind.Local,
]);

/**
 * Состояние расшифровки: шесть значений, из них четыре незакрытых.
 *
 * Состояний больше, чем «идёт / кончилось», потому что все различия —
 * **границы**, а не оттенки прогресса, и по ним решается судьба задачи при
 * перезапуске API (дизайн, 2.4): в `queued` наружу не ушло ничего и работа
 * не начата, в `extracting` работа идёт на нашей машине, в `sending` байты
 * в пути, в `running` работа у провайдера и нам есть чем его опросить.
 * Прерванное извлечение повторяется молча, прерванная отправка наружу —
 * нет, и без отдельных состояний эти два случая были бы неотличимы.
 */
export const transcriptionStateEnum = pgEnum('transcription_state', [
  TranscriptionState.Queued,
  TranscriptionState.Extracting,
  TranscriptionState.Sending,
  TranscriptionState.Running,
  TranscriptionState.Done,
  TranscriptionState.Failed,
]);

/** Незакрытые состояния: по ним стоят оба частичных индекса. */
const UNCLOSED = sql`('queued','extracting','sending','running')`;

/**
 * Задача расшифровки записи созвона (дизайн расшифровки, раздел 2.1).
 *
 * Единственная новая таблица итерации: ни `summaries`, ни
 * `summary_task_drafts`, ни `chronicle_entries` не меняются. Это и есть
 * главное решение дизайна (раздел 2.2) — **саммари рождается из готового
 * текста**, а пока текста нет, в системе есть только задача расшифровки.
 * Поэтому `summary_id` обнуляемо: у первой расшифровки саммари ещё не
 * существует, у повторной — уже есть.
 *
 * **Колонки текста нет.** Расшифрованный текст не задерживается в задаче
 * ни на шаг: он приходит из порта в память, уезжает в
 * `chronicle_entries.content` той же транзакцией и больше нигде не живёт.
 * Вторая копия текста — ровно то, от чего избавляет отсутствие колонки
 * текста у `summaries`.
 *
 * **Колонки длительности нет**, хотя `ffprobe` её знает: ни один экран и
 * ни одна проверка её не читают — предел длительности принадлежит службе
 * и приходит её отказом, а размер дорожки система знает точно
 * (`audio_bytes`). Колонка, которую никто не читает, — это обязанность
 * держать её согласованной бесплатно.
 *
 * **Имени присланного файла нет**: имена файлов на машинах людей нередко
 * говорят больше, чем содержимое (решение первой итерации про текстовый
 * файл). Расширение на диске выводится из `upload_type`.
 *
 * Инвариант «`summary_id is null` **тогда и только тогда**, когда заполнены
 * `occurred_on` и `title`» держит репозиторий, а не база: у него две
 * разные ручки — первая расшифровка принимает паспорт, повторная нет.
 */
export const transcriptionJobs = pgTable(
  'transcription_jobs',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    /**
     * Проект есть отдельно от саммари, потому что право проверяется **до**
     * появления саммари, и проверять его нужно по проекту. Когда саммари
     * появилось, проект у них один и тот же: обе строки создаются одной
     * транзакцией с одним `projectId`.
     */
    projectId: uuid('project_id')
      .notNull()
      .references(() => projects.id, { onDelete: 'restrict' }),
    /** `null` — первая расшифровка: саммари ещё нет (дизайн, 2.2). */
    summaryId: uuid('summary_id').references(() => summaries.id, { onDelete: 'restrict' }),
    /**
     * Чьим правом идёт работа.
     *
     * Фоновый прогон не действует «от системы»: он собирает `RequestSubject`
     * по этому идентификатору и зовёт репозитории через него. Второй путь
     * записи «от системы, без проверки» был бы дыркой в модели прав, а
     * отозванная к окончанию выдача означает, что текст не ляжет, — это
     * свойство, а не дефект (дизайн, 6.4 и 6.5).
     */
    requestedBySubjectId: uuid('requested_by_subject_id')
      .notNull()
      .references(() => subjects.id, { onDelete: 'restrict' }),
    state: transcriptionStateEnum('state').notNull().default(TranscriptionState.Queued),
    transcriber: transcriberKindEnum('transcriber').notNull(),
    model: text('model').notNull(),
    /**
     * Имя узла, куда ушла запись. Полный адрес и ключ сюда не попадают
     * никогда: ответ на «куда уходили наши созвоны в ноябре» обязан
     * читаться из базы, а не из `.env`, который с тех пор поправили.
     */
    host: text('host'),
    /**
     * Загруженный человеком файл — первая тройка колонок про файлы.
     *
     * Их **две**, и одной не выражается: до службы едет не загруженный
     * файл, а извлечённая дорожка, размер и тип у них разные, и оба нужны
     * — первая тройка отвечает на «что загрузили», вторая на «что ушло
     * наружу». Это различие двух пределов в модели данных (дизайн, 3.6).
     *
     * `upload_path` обнуляем: `null` означает «этого файла больше нет», и
     * у каждого дошедшего до `done` саммари это обычное состояние —
     * исходник убирается при укладке текста (решение владельца 2).
     */
    uploadPath: text('upload_path'),
    /**
     * Размер и тип загруженного **не обнуляемы** и остаются после
     * удаления файла: у каждого закончившегося успехом саммари исходника
     * больше нет, и единственный ответ на вопросы «что я загружал» и
     * «почему дорожка такая короткая» — эти две колонки.
     */
    uploadBytes: integer('upload_bytes').notNull(),
    uploadType: text('upload_type').notNull(),
    /**
     * Звуковая дорожка — вторая тройка: то, что уедет службе и что
     * слушает человек.
     *
     * Обнуляема: до извлечения дорожки нет. Когда загруженный файл служба
     * принимает как есть, извлечение пропускается и `audio_path` равен
     * `upload_path` — **та же строка пути**, не копия файла. Отсюда прямое
     * правило чтения: `audio_path is null` значит «отдавать службе нечего,
     * работа ещё не сделана», а не «записи нет». И отсюда же ловушка
     * уборки: **равенство путей означает «убирать нечего»**, иначе уборка
     * на `done` унесла бы единственный файл саммари.
     */
    audioPath: text('audio_path'),
    audioBytes: integer('audio_bytes'),
    audioType: text('audio_type'),
    /**
     * Паспорт будущего саммари, введённый человеком в форме.
     *
     * Нужен ровно до рождения саммари; у повторной расшифровки его нет —
     * саммари уже есть, и его паспорт это паспорт записи хроники. Тип
     * `date` с `mode: 'string'` — тот же, что у
     * `chronicle_entries.occurred_on`, иначе день по дороге сменил бы
     * представление.
     */
    occurredOn: date('occurred_on', { mode: 'string' }),
    title: text('title'),
    /**
     * `operation_id` провайдера. Пишется в той же транзакции, что переход
     * в `running`, и это не формальность: строка `running` без него — это
     * строка, которую нечем опросить.
     */
    externalId: text('external_id'),
    /**
     * Код отказа из контракта, без тела чужого ответа: в нём бывают и
     * подробности о ключе, и фрагменты присланного.
     */
    failureCode: text('failure_code'),
    startedAt: timestamp('started_at', { withTimezone: true }).notNull().defaultNow(),
    /**
     * Когда запись покинула машину — отдельно от `started_at`, который
     * говорит, когда её приняли у человека. Между ними лежит и очередь, и
     * извлечение, и на вопрос «когда созвон покинул машину» отвечает
     * только эта колонка.
     */
    sentAt: timestamp('sent_at', { withTimezone: true }),
    finishedAt: timestamp('finished_at', { withTimezone: true }),
  },
  (table) => [
    // Одна незакрытая расшифровка на саммари. Образец —
    // `address_incidents_open`: правило живёт в базе, а не в памяти
    // процесса, и перезапуск API его не теряет.
    //
    // Предикат перечисляет **все четыре** незакрытых состояния: пропусти
    // `extracting`, и во время извлечения можно было бы запустить вторую
    // расшифровку того же саммари — два `ffmpeg` на один файл и две
    // записи в один `content`.
    //
    // Тонкость, которую иначе прочтут как дырку: в PostgreSQL `NULL` в
    // уникальном индексе не конфликтует с `NULL`, поэтому **первых
    // расшифровок у проекта может идти сколько угодно**. Так и нужно: три
    // загруженные записи — это три будущих саммари. Уникум защищает ровно
    // то, что нуждается в защите.
    //
    // Почему не `finished_at is null`, как у инцидента: предикат по
    // времени потерял бы разницу между «в очереди», «извлекаем» и «байты
    // в пути», а это ровно то, по чему принимается решение при
    // перезапуске API (дизайн, 2.4).
    uniqueIndex('transcription_jobs_active')
      .on(table.summaryId)
      .where(sql`${table.state} in ${UNCLOSED}`),
    // Очередь прогона: частичный индекс делает тик дешёвым при любом
    // размере истории.
    index('transcription_jobs_queue')
      .on(table.startedAt)
      .where(sql`${table.state} in ${UNCLOSED}`),
    // История расшифровок проекта и экранная очередь: частичные индексы
    // выше видят только незакрытые строки.
    index('transcription_jobs_project_started').on(table.projectId, table.startedAt.desc()),
  ],
);

/** Строка задачи расшифровки. */
export type TranscriptionJobRow = typeof transcriptionJobs.$inferSelect;
