import { json, urlencoded, type RequestHandler } from 'express';

/**
 * Предел разбираемого тела запроса в JSON.
 *
 * Считается от контракта, а не выбирается на глаз. Самое длинное
 * текстовое поле — содержимое `.env` при импорте переменных (1 Ми
 * знаков); знак в UTF-8 занимает до трёх байт, плюс экранирование
 * кавычек и переводов строк. Четыре мегабайта покрывают его целиком,
 * и ровно это важно: предел разборщика обязан быть **выше** предела
 * схемы, иначе длинное тело получает неназванное
 * `request entity too large` вместо `400` с полем и причиной.
 *
 * Умолчание body-parser — 100 КиБ, и оно было ниже контракта: импорт
 * `.env` не проходил вовсе, а саммари отваливалось на пятидесяти тысячах
 * знаков по-русски (два байта на знак), хотя контракт обещает 65 536.
 *
 * Запись здесь не действует на загрузку записи созвона: та едет сырым
 * телом своего медиа-типа, разборщиков не касается вовсе и считает свои
 * байты сама (`recording-store.ts`).
 */
export const JSON_BODY_LIMIT = '4mb';

/**
 * Разборщики тела с нашим пределом вместо умолчания.
 *
 * Нужны оба и в этом порядке: Nest по умолчанию ставит ровно такую пару,
 * и отключать её (`bodyParser: false`) можно только вместе с заменой —
 * иначе формы и JSON перестали бы разбираться совсем.
 */
export function bodyParsers(): RequestHandler[] {
  return [
    json({ limit: JSON_BODY_LIMIT }),
    urlencoded({ extended: true, limit: JSON_BODY_LIMIT }),
  ];
}
