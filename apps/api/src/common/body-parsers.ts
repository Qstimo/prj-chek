import { MAX_INTAKE_CONTENT_CHARS } from '@cairn/shared';
import { json, text, urlencoded, type RequestHandler } from 'express';

/**
 * Предел разбираемого тела запроса в JSON.
 *
 * Считается от контракта, а не выбирается на глаз. Самое длинное
 * текстовое поле — содержимое `.env` при импорте переменных (1 Ми
 * знаков); знак в UTF-8 занимает до трёх байт, плюс экранирование
 * кавычек и переводов строк. Четыре мегабайта покрывают его целиком,
 * и ровно это важно: предел разборщика обязан быть **выше** предела
 * схемы, иначе длинное тело получает неназванное
 * `request entity too large` вместо `400` с полем и причиной.
 *
 * Умолчание body-parser — 100 КиБ, и оно было ниже контракта: импорт
 * `.env` не проходил вовсе, а саммари отваливалось на пятидесяти тысячах
 * знаков по-русски (два байта на знак). Предел текста саммари с тех пор
 * вырос до 256 Ки знаков (`MAX_CHRONICLE_CONTENT_CHARS`) — четыре часа
 * созвона, — и четыре мегабайта покрывают и его: 256 Ки знаков кириллицы
 * это полмегабайта.
 *
 * Запись здесь не действует на загрузку записи созвона: та едет сырым
 * телом своего медиа-типа, разборщиков не касается вовсе и считает свои
 * байты сама (`recording-store.ts`).
 */
export const JSON_BODY_LIMIT = '4mb';

/**
 * Предел тела приёмного канала, принимающего сводку чистым текстом.
 *
 * Считается от своего поля контракта и в **байтах**, а поле контракта
 * мерит **знаки** — ровно на этом и ломалось: предел стоял равным числу
 * знаков (`64kb`), а знак кириллицы в UTF-8 занимает два байта, и русский
 * текст получал неназванное `request entity too large` вдвое раньше, чем
 * схема сказала бы «слишком длинно». Три байта на знак — тот же запас,
 * которым считается предел загружаемого файла в вебе.
 */
export const INTAKE_TEXT_LIMIT = `${MAX_INTAKE_CONTENT_CHARS * 3}b`;

/**
 * Разборщик чистого текста приёмного канала (спека 5.1).
 *
 * Стоит на своём типе содержимого и чужих тел не касается: чем меньше
 * глобальных разборщиков, тем меньше мест, где следующий поток случайно
 * съест чужое тело. Сырое тело записи созвона через него не проходит —
 * у неё свой медиа-тип.
 */
export function intakeTextParser(): RequestHandler {
  return text({ type: 'text/plain', limit: INTAKE_TEXT_LIMIT });
}

/**
 * Разборщики тела с нашим пределом вместо умолчания.
 *
 * Нужны оба и в этом порядке: Nest по умолчанию ставит ровно такую пару,
 * и отключать её (`bodyParser: false`) можно только вместе с заменой —
 * иначе формы и JSON перестали бы разбираться совсем.
 */
export function bodyParsers(): RequestHandler[] {
  return [
    json({ limit: JSON_BODY_LIMIT }),
    urlencoded({ extended: true, limit: JSON_BODY_LIMIT }),
  ];
}
