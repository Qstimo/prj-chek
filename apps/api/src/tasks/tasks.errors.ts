import { TASK_ALREADY_PLACED, TASK_PLACED } from '@cairn/shared';
import { ConflictException } from '@nestjs/common';

/**
 * Задачу просят положить в версию, а она уже стоит в другой.
 *
 * `409`, а не `404`: субъект видит и задачу, и версию — отрицать их
 * существование бессмысленно. Состояние мешает операции, и именно это
 * сказано кодом: интерфейс по нему предлагает перенос вместо размещения.
 *
 * Запрет держит и база — частичный уникум по `task_id`, — а это исключение
 * переводит его в названный отказ: без него нарушение уникума пришло бы
 * ошибкой драйвера, то есть `500` вместо объяснения.
 */
export class TaskAlreadyPlacedError extends ConflictException {
  constructor() {
    super({ code: TASK_ALREADY_PLACED, message: 'Задача уже стоит в версии роадмапа.' });
  }
}

/**
 * Задачу просят удалить, а она стоит в версии.
 *
 * Отказ, а не каскад: удаление из реестра меняло бы прогресс версии с
 * другого экрана и молча. Сначала вынь из версии — тогда и видно, что
 * прогресс изменился, и видно, кто это сделал.
 */
export class TaskPlacedError extends ConflictException {
  constructor() {
    super({ code: TASK_PLACED, message: 'Задача стоит в версии: сначала выньте её из версии.' });
  }
}
