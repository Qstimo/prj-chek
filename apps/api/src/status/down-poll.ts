/** Шаг частого опроса лежащих адресов по умолчанию, в секундах. */
export const DEFAULT_DOWN_POLL_SECONDS = 60;

/**
 * Как часто переспрашивать адреса с открытым падением.
 *
 * Сводный прогон идёт раз в четверть часа, и этого хватает, чтобы узнать
 * о падении, но не хватает, чтобы знать его длительность: любой отрезок в
 * истории оказывался кратен интервалу опроса, а вилка возвращения —
 * пятнадцатиминутной. Пока падение открыто, его адреса спрашиваются
 * отдельно и часто — остальные при этом не трогаются вовсе.
 *
 * `0` означает «только сводный прогон»: здесь, в отличие от переспроса,
 * выключатель нужен — частый опрос ходит в сеть сам по себе. Мусор и
 * отрицательное значение означают умолчание, а не «никогда».
 */
export function downPollSecondsOf(value: string | undefined): number {
  if (value !== undefined && value.trim() === '0') {
    return 0;
  }

  const seconds = Number(value);

  return Number.isFinite(seconds) && seconds > 0
    ? Math.round(seconds)
    : DEFAULT_DOWN_POLL_SECONDS;
}
