/**
 * Какой из адресов имени считать тем самым.
 *
 * Первый по возрастанию строк: привязка у окружения одна, а резолверы
 * ротируют порядок ответа — пока бралась первая запись, привязка плясала
 * от прогона к прогону вместе с ней. Сравнение строковое, а не числовое,
 * и это намеренно: от правила нужна устойчивость выбора, а не порядок
 * адресов по величине.
 *
 * Своим файлом, а не функцией хранилища: правило нужно и записи статуса,
 * и слепку падения, который стучится в порты той же машины, — второй его
 * экземпляр разошёлся бы с первым, и проба описывала бы не тот адрес, на
 * который смотрит привязка.
 */
export function canonicalIpOf(ips: string[]): string | null {
  return [...ips].sort()[0] ?? null;
}
