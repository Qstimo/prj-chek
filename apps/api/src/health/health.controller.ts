import { Controller, Get } from '@nestjs/common';

/** Ответ проверки живости. */
export interface HealthResponse {
  /** Единственное значение: приложение приняло запрос и ответило. */
  status: 'ok';
}

/**
 * Проверка живости приложения.
 *
 * Адрес открыт намеренно: его опрашивает Docker изнутри контейнера, сессии
 * у него нет. Ответ не содержит сведений о системе — ни версии, ни состояния
 * базы, — поэтому его публичность ничего не раскрывает.
 *
 * База намеренно не проверяется: недоступность базы не повод убивать и
 * перезапускать приложение, которое поднимется в то же нерабочее состояние.
 * За готовность базы отвечает её собственная проверка в docker-compose.
 */
@Controller('health')
export class HealthController {
  /** Отвечает, пока процесс обслуживает запросы. */
  @Get()
  check(): HealthResponse {
    return { status: 'ok' };
  }
}
